// ЗАКОН СТЕПЕНИ ДВОЙКИ — ОДНА ДВЕРЬ, И СУДИТ ЕЁ КОМПИЛЯТОР.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
// --------------------------
// «Везде степени двойки» — закон владельца и опора всего адресного хозяйства:
// адрес клетки считается индексом без деления, заворот тора — маской, страница
// субвокселей — сдвигом, бит в SubMask — смещением. CANON S15.2 говорит про это
// прямо: степени двойки — «не эстетика, а отсутствие делений».
//
// А держался этот закон НИЧЕМ. Перепись 2026-10-01:
//
//     grep -rn 'static_assert' src/ | grep -E '& *\(.*- *1\) *== *0'
//
// нашла ДВА вхождения на весь проект — `kPowerCutCoarseDim@src/game/combat.h` и
// `kSpeechMemorySlots@src/game/speech.h`. Оба периферийные. У САМОГО ЯДРА —
// `kMacroDim`, `kSubDim`, `kSubVoxels`, `kNpcPoolSize`, `kInvSlots`,
// `kRootLights`, `kRootPropInstances`, `kRootAntouragePoints`, `kRootParticles`,
// `kLatticeDim` — утверждения о степени двойки не стояло НИ ОДНОГО.
//
// Это не гипотетическая дыра, и цена у неё асимметричная: на степени двойки
// деление и маска дают ПОБИТОВО ОДНО И ТО ЖЕ, поэтому рантайм-тест такого
// нарушения не поймает никогда — он поймает его только на НЕ-степени, то есть
// в тот день, когда кап уже поменяли и мир уже тихо врёт. Класс дефекта
// описан у соседнего проекта дословно: «на мире-степени-двойки деление и маска
// дают побитово одно и то же», и свидетеля у закона не было, потому что
// краснеть ему было не на чем.
//
// Поэтому свидетель здесь — `static_assert`: нарушение, которое невозможно
// СОБРАТЬ. Прогона не нужно, флачить нечему, подогнать нельзя, и судит он
// одинаково на macOS/Clang и на MSVC — что важно отдельно, пока виндовая нога
// CI стоит по биллингу (AGENTS.md §Build).
//
// ЦЕНА ВКЛЮЧЕНИЯ — O(1)
// ---------------------
// Один `<bit>` и две `constexpr`-функции без тел, зависящих от капов. Ни одной
// именованной переменной с инициализатором (это тот самый класс, который у
// соседнего проекта стоил 55.6 с и 6.58 ГиБ на пустом TU).
#pragma once
#include <bit>
#include <cstdint>
#include <type_traits>

namespace giga {

// Степень двойки? ОДНА ДВЕРЬ, шаблоном, а не парой перегрузок.
//
// Перегрузки `is_po2(uint64_t)` / `is_po2(int64_t)` здесь стояли и были СНЕСЕНЫ
// в тот же час: капы в этом дереве объявлены кто `int`, кто `std::uint32_t`
// (`kMacroDim` — int, `kNpcPoolSize` — uint32), а `int` конвертируется в оба
// параметра одинаково хорошо — вызов стал неоднозначным, и файл не собрался.
// Это ровно та ошибка, которую контур и должен ловить: закон о капах обязан
// принимать кап любой ширины, не спрашивая автора, какой он подписанности.
//
// Ноль степенью двойки НЕ является, и это не придирка: кап 0 — буфер, в который
// нельзя положить ничего, а маска `0 - 1` развернулась бы во все единицы и
// адресовала бы весь мир. Отрицательное капом не бывает, и отказ ему явный, а
// не через приведение к беззнаковому: оно превратило бы −1 в 0xFFFF…FF и
// ответило бы «нет» по СЛУЧАЙНОЙ причине вместо верной.
template <class T>
inline constexpr bool is_po2(T v) {
    static_assert(std::is_integral_v<T>, "кап — целое число");
    if constexpr (std::is_signed_v<T>) {
        if (v <= 0) return false;
    }
    return std::has_single_bit(static_cast<std::uint64_t>(v));
}

// log2 капа — для тех мест, где рядом с константой хочется показать ВЫВОД
// («128 = 2^7»), а не повторить число словами. Вне степени двойки не
// определён, и спрашивать его там нечего — потому вызов стоит рядом со своим
// `static_assert(is_po2(...))`, а не вместо него.
inline constexpr int po2_log2(std::uint64_t v) { return std::countr_zero(v); }

// ОДНА СТРОКА НА КАП — вместо трёх руками. Сообщение называет и константу, и
// закон, и то, что именно сломается: иначе красный `static_assert` сообщает
// «не степень двойки» и заставляет следующего агента искать, чем это плохо.
#define GIGA_PO2(CAP)                                                          \
    static_assert(::giga::is_po2(CAP),                                         \
                  #CAP ": кап обязан быть степенью двойки (CANON S15.2 — "     \
                       "«не эстетика, а отсутствие делений»). На степени "     \
                       "двойки адрес берётся маской и сдвигом; стоит ей "      \
                       "уйти — заворот тора, индекс страницы и бит маски "     \
                       "начинают требовать деления, и ни один рантайм-тест "   \
                       "этого не поймает, потому что до смены числа оба "      \
                       "написания давали ПОБИТОВО одно и то же.")

} // namespace giga
