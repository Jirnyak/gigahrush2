// Часы Гигахруща: такт → вахта → цикл → эпоха.
//
// В этом мире НЕТ СОЛНЦА — нет дней, нет ночей, нет рассветов ([CANON.md] S15).
// Ритм задаёт не небо, а дом: освещение, гудки, смены вахт. Поэтому здесь нет
// ни «часа», ни «суток»: заимствовать слова у мира, которого под землёй не
// существует, значит обещать игроку то, чего он никогда не увидит.
//
// ЧТО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ. Он ничем не управляет и никого не будит. Время —
// это счётчик тиков и чистые функции над ним; кто хочет знать который час,
// спрашивает сам. Системы времени, которая рассылает события и дёргает свет,
// не существует и не должно появиться: свет гасит ЩИТОК по своей программе
// (S15.4), гудок издаёт ПРОП-ревун, табло рисует ПРОП. Здесь только арифметика.
#pragma once

#include <cstdint>

#include "core/tick.h"

namespace giga {

// ---------------------------------------------------------------------------
// Лестница
// ---------------------------------------------------------------------------
// ТАКТ ВЫВЕДЕН, А НЕ НАЗНАЧЕН, и вот из чего.
//
// До S15 в игре был ровно один «игровой час» — `kGameHourSec = 60` секунд
// (умершей комнатной регенерации), от которого считалась скорость восстановления в
// комнатах. Шестьдесят секунд при 125 Гц — это 7500 тиков. Ближайшая к 7500
// степень двойки — 8192 (2^13): до неё 692 тика, а до 4096 — 3404, то есть
// вчетверо дальше. Берём 8192.
//
// Цена округления: такт длиннее прежнего часа на 9.2 %. Это единственное
// место, где S15 меняет ощущаемый темп игры, и платим мы за то, что ВЕСЬ
// календарь считается сдвигами.
inline constexpr int kTactShift = 13;

// Каждый следующий уровень — ВОСЕМЬ предыдущих, то есть ровно ТРИ БИТА.
// Тройка не эстетика: три бита — это три лампы, и табло вахты (S15.3) читается
// как прибор, а не как часы. Четыре уровня по три бита = 12 бит, которых
// хватает на 9.3 часа непрерывной игры до переполнения старшего.
inline constexpr int kLevelBits = 3;

inline constexpr int kWatchShift = kTactShift + kLevelBits;   // 16
inline constexpr int kCycleShift = kWatchShift + kLevelBits;  // 19
inline constexpr int kEpochShift = kCycleShift + kLevelBits;  // 22

inline constexpr std::uint64_t kTactTicks = 1ull << kTactShift;    //     8 192
inline constexpr std::uint64_t kWatchTicks = 1ull << kWatchShift;  //    65 536
inline constexpr std::uint64_t kCycleTicks = 1ull << kCycleShift;  //   524 288
inline constexpr std::uint64_t kEpochTicks = 1ull << kEpochShift;  // 4 194 304

// Даром доставшееся свойство, которое стоит записать, чтобы его не потеряли:
// шаг тика — РОВНО 8 мс ([core/tick.h] `kSimStepMs`, и это единственная причина,
// по которой частота 125, а не 120). Восемь — это 2^3, поэтому каждый уровень
// лестницы оказывается степенью двойки и в ТИКАХ, и в МИЛЛИСЕКУНДАХ:
//   такт  2^13 тиков = 2^16 мс = 65.536 с
//   вахта 2^16 тиков = 2^19 мс =  8.74 мин
//   цикл  2^19 тиков = 2^22 мс = 69.9  мин
//   эпоха 2^22 тиков = 2^25 мс =  9.32 ч
// Значит и таймеры в целых миллисекундах (самосбор, кулдауны, статусы) смогут
// сверяться с календарём сдвигом, а не делением, если это когда-нибудь
// понадобится.
static_assert(kSimStepMs == 8,
              "лестница времени опирается на то, что тик — ровно 8 мс = 2^3; "
              "при другом шаге уровни перестают быть степенями двойки в "
              "миллисекундах, и половина смысла S15 теряется");
static_assert(kWatchTicks == kTactTicks * 8 && kCycleTicks == kWatchTicks * 8 &&
                  kEpochTicks == kCycleTicks * 8,
              "каждый уровень обязан быть ровно восемью предыдущими: на этом "
              "стоит и табло из трёх ламп, и чтение цифры одной маской");

// ---------------------------------------------------------------------------
// Чтение времени — только сдвиги и маски, ни одного деления
// ---------------------------------------------------------------------------
// Ради этого лестница и построена на 2^n. Деление 64-битного счётчика на
// не-степень двойки стоит десятки тактов и делается на КАЖДОМ обращении к
// часам; сдвиг стоит один. Гейт S15 требует, чтобы в вычислении времени не
// встречалось ни `%`, ни `/`.

inline constexpr std::uint64_t watch_tact(std::uint64_t tick) { return tick >> kTactShift; }
inline constexpr std::uint64_t watch_watch(std::uint64_t tick) { return tick >> kWatchShift; }
inline constexpr std::uint64_t watch_cycle(std::uint64_t tick) { return tick >> kCycleShift; }
inline constexpr std::uint64_t watch_epoch(std::uint64_t tick) { return tick >> kEpochShift; }

// Цифра уровня — то, что показывает своя тройка ламп на табло: 0..7.
inline constexpr int kLevelMask = (1 << kLevelBits) - 1;  // 7

inline constexpr int watch_tact_digit(std::uint64_t tick) {
    return static_cast<int>(watch_tact(tick) & kLevelMask);
}
inline constexpr int watch_watch_digit(std::uint64_t tick) {
    return static_cast<int>(watch_watch(tick) & kLevelMask);
}
inline constexpr int watch_cycle_digit(std::uint64_t tick) {
    return static_cast<int>(watch_cycle(tick) & kLevelMask);
}

// ---------------------------------------------------------------------------
// Фаза освещения
// ---------------------------------------------------------------------------
// ЧЕТЫРЕ ФАЗЫ ПО ДВЕ ВАХТЫ (решение владельца 2026-08-20): полный → рабочий →
// дежурный → тьма, по 17.5 минуты каждая. Две вахты — это 2^17 тиков, то есть
// фаза читается тем же сдвигом, что и всё остальное.
//
// САМА ПО СЕБЕ ЭТА ФУНКЦИЯ НИЧЕГО НЕ ГАСИТ. Она отвечает на вопрос «которая
// сейчас фаза», а решает, что с этим делать, ПРОГРАММА ЩИТКА: у каждого щитка
// свой сдвиг фазы и свои уровни, поэтому районы этажа гаснут по-своему и
// рассинхрон освещения сам становится сигналом «в том крыле что-то не так»
// (S15.4). Здесь — только номер фазы.
inline constexpr int kLightPhases = 4;
inline constexpr int kLightPhaseShift = kWatchShift + 1;  // 17 — две вахты
inline constexpr std::uint64_t kLightPhaseTicks = 1ull << kLightPhaseShift;

static_assert(kLightPhaseTicks * kLightPhases == kCycleTicks,
              "четыре фазы обязаны укладываться в цикл ровно, иначе освещение "
              "поедет относительно вахт и табло начнёт врать");

inline constexpr int watch_light_phase(std::uint64_t tick) {
    return static_cast<int>((tick >> kLightPhaseShift) & (kLightPhases - 1));
}

// ---------------------------------------------------------------------------
// Границы
// ---------------------------------------------------------------------------
// «Наступила ли смена вахты» — это СРАВНЕНИЕ ДВУХ НОМЕРОВ, а не событие,
// которое кто-то обязан разослать (S15.3). Ревун, табло и худ спрашивают сами;
// если рассылка когда-нибудь понадобится, она идёт в существующую шину
// ([game/event_bus.h]), а не в свою.
//
// Осторожно с местом вызова: сим делает до восьми подшагов на кадр, поэтому
// сравнивать надо внутри сим-цикла. Спросив раз в кадр, можно увидеть только
// то, что оставил последний подшаг.
inline constexpr bool watch_tact_border(std::uint64_t prev, std::uint64_t now) {
    return watch_tact(prev) != watch_tact(now);
}
inline constexpr bool watch_watch_border(std::uint64_t prev, std::uint64_t now) {
    return watch_watch(prev) != watch_watch(now);
}
inline constexpr bool watch_cycle_border(std::uint64_t prev, std::uint64_t now) {
    return watch_cycle(prev) != watch_cycle(now);
}
inline constexpr bool watch_light_phase_border(std::uint64_t prev, std::uint64_t now) {
    return watch_light_phase(prev) != watch_light_phase(now);
}

// ---------------------------------------------------------------------------
// Мост в секунды — ТОЛЬКО для тех, кто уже живёт в секундах
// ---------------------------------------------------------------------------
// Нужен ровно затем, чтобы `kGameHourSec` мог умереть: его единственный
// потребитель — строка таблицы восстановления в комнате, считающая «столько-то
// в секунду» (умершая комнатная регенерация). Новый код обязан жить в тиках; секунды здесь
// — совместимость, а не второе представление времени.
inline constexpr float kTactSeconds =
    static_cast<float>(kTactTicks) / static_cast<float>(kSimHz);  // 65.536

} // namespace giga
