//
// ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
// --------------------------
// AGENTS.md требует «POD components (zero behavior/virtual functions), dense
// contiguous memory buffers (SoA / flat arrays), zero per-frame hot-path
// allocations». Требование верное и держалось оно ПРОЗОЙ.
//
// Текстовый запрет на слово `std::vector` здесь НЕ РАБОТАЕТ, и это проверено
// замером, а не предположено. В `src/` 504 вхождения `std::vector`, и среди
// них `types_`/`masks_` в `MacroGrid` — те самые ПЛОСКИЕ МАССИВЫ МИРА на 4 и
// 128 МиБ, аллоцированные один раз в конструкторе и не растущие никогда. Они
// ЗАКОННЫ: вектор длиной мира есть плоский массив, а не контейнер. Запрет по
// слову пинил бы их наравне с настоящими дефектами и заставлял бы править пин
// при каждом рефакторе — то есть учил бы обходить гейт, а не чинить код.
//
// Закон говорит о том, что лежит ВНУТРИ СТРУКТУРЫ. Текстовый запрет — о том,
// что написано В ФАЙЛЕ. Это разные утверждения, и верное из них проверяется
// типом:
//
//     `is_trivially_copyable` спрашивает ЧЛЕНОВ и обойти себя не даёт ни одним
//     написанием — ни один heap-контейнер стандартной библиотеки тривиально
//     копируемым не бывает.
//
// Поэтому контур ставится на СТРОКУ МИРА — структуру, которая умножается на
// кап, ложится в сейв или едет пакетом, — и нарушение такой структуры
// перестаёт СОБИРАТЬСЯ, назвав виноватый тип поимённо.
//
// ЧТО КОНТУР НЕ ДЕЛАЕТ
// --------------------
// Он не вычищает ООП: его в дереве уже нет. Перепись 2026-10-01 —
//
//     grep -rnE 'virtual |class .*:.*public' src/   →   0
//
// ноль виртуальных и ноль наследований во всём `src/`. Контур ЗАМОРАЖИВАЕТ
// ДОСТИГНУТЫЙ НОЛЬ, и это сознательно более сильная форма, чем храповик:
// храповик нужен там, где долг непуст, а над нулём ставится стена. То же и с
// `is_trivially_copyable` — 25 таких утверждений в дереве уже стояли, но
// расставлены они были вразброс и вручную, то есть новая структура вставала
// без них молча.
//
// ДЫРА КОНТУРА НАЗВАНА ВСЛУХ
// --------------------------
// У стены ровно одна: новый тип можно завести, ПРОСТО НЕ ПОЗВАВ макрос. Её и
// только её закрывает текстовый прибор `tools/check_row_law.cmake` (ctest
// `row_law`), который требует контур у каждой `struct` в перечисленных там
// заголовках-строках. Судить форму типа второй раз текстом было бы вторым
// ответом на один вопрос; прибор судит ПОЛНОТУ, а не форму.
//
// ЦЕНА ВКЛЮЧЕНИЯ — O(1): один `<type_traits>`, ни одного тела, ни одной
// именованной переменной с инициализатором.
//
// КУДА СТАВИТЬ ВЫЗОВЫ
// -------------------
// Блоком ВНИЗУ файла, рядом с `#include "core/row_law.h"`, а не у каждой
// структуры. Довод не стилистический: включение, вставленное наверх заголовка,
// сдвигает его содержимое на строку и гноит каждую ссылку документов в этот
// файл — у соседнего проекта одна такая вставка в 17 заголовков сломала 10
// ссылок. Внизу сдвигать нечего.
#pragma once
#include <type_traits>

// GIGA_ROW(T) — контур строки мира. Четыре утверждения, и каждое называет
// закон, который оно держит, и тот род члена, который его ломает: красный
// `static_assert`, сообщающий «not trivially copyable», заставляет следующего
// агента искать виноватого руками.
#define GIGA_ROW(T)                                                            \
    static_assert(std::is_trivially_copyable_v<T>,                             \
                  #T ": строка мира обязана переживать memcpy и ложиться в "   \
                     "сейв без своего сериализатора (AGENTS.md: POD "          \
                     "components, SoA/flat arrays). Её сломал член, который "  \
                     "тривиально копируемым не бывает: vector, string, map, "  \
                     "unique_ptr, shared_ptr, function. Вместо него — "        \
                     "плоский массив с ИМЕНОВАННЫМ капом и явным счётом.");    \
    static_assert(std::is_standard_layout_v<T>,                                \
                  #T ": у строки мира раскладка обязана быть предсказуемой — " \
                     "её читают шейдер через SSBO, сейв через байты и шов "    \
                     "GPU через staging. Ломают ссылка членом, смешанные "     \
                     "public/private данные и наследование.");                 \
    static_assert(!std::is_polymorphic_v<T>,                                   \
                  #T ": виртуальных на горячих данных не бывает (AGENTS.md: "  \
                     "zero behavior/virtual functions). vtable кладёт в "      \
                     "строку указатель ПРОЦЕССА — такую строку нельзя ни "     \
                     "сохранить, ни отправить пакетом, ни отдать GPU.");       \
    static_assert(std::is_trivially_destructible_v<T>,                         \
                  #T ": исчезновение строки есть ЗАНУЛЕНИЕ СЛОТА, а не "      \
                     "обход деструкторов. Пул с переработкой (CANON S11) "     \
                     "переиспользует слот записью поверх; деструктор, которому "\
                     "есть что делать, означает, что в строке живёт ресурс, "  \
                     "и пул начал бы его течь.");                              \
    static_assert(true, "") /* макрос требует ';' на месте вызова */

// GIGA_ROW_BYTES(T, BYTES) — контур ПЛЮС размер, когда размер НАЗВАН числом
// (в SKELETON.md, в шапке или в расчёте капа). Нужен затем, что `sizeof` —
// это ЛОВУШКА НА КОСТЫЛЬ: пришил служебное поле к строке, которая умножается
// на кап, — размер уехал, сборка красная, и спрятать это некуда.
//
// CANON S11 требует «константа обязана выводиться», и байты строки — тот же
// случай: 6 Б × 64 слота = 384 Б инвентаря есть ВЫВОД, а не наблюдение.
#define GIGA_ROW_BYTES(T, BYTES)                                               \
    GIGA_ROW(T);                                                               \
    static_assert(sizeof(T) == (BYTES),                                        \
                  #T ": размер этой строки НАЗВАН числом, и он разъехался. "   \
                     "Либо поле добавлено осознанно — поправь число здесь И "  \
                     "там, где оно названо (паспорт памяти в SKELETON.md); "   \
                     "либо в раскладке дыра выравнивания, и тогда узкие поля " \
                     "пакуются ВМЕСТЕ: одинокий u8 рядом с i32 не экономит "   \
                     "ничего, это те же 8 байт.");                             \
    static_assert(true, "")
