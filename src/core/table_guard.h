//
// ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
// --------------------------
// Таблица, чей порядок строк обязан повторять энум, — молчаливая ловушка:
// индексируется она `enum` → `int`, а держится ПОРЯДКОМ, который компилятор не
// видит. Переставил, вставил или удалил значение энума — таблица отвечает на
// чужой вопрос, и ни сборка, ни тест этого не замечают.
//
// Перепись 2026-10-01, мера —
//
//     grep -rn 'sizeof(k[A-Za-z]*) */ *sizeof' src/ --include='*.cpp' --include='*.h'
//
// нашла в дереве **14** таких таблиц, и у всех четырнадцати проверена ровно
// ДЛИНА («одна строка на значение энума»). Проверок ПОРЯДКА — мера
// `grep -rn 'rows_in_enum_order' src/` → **0** на весь проект.
//
// Длина слабее порядка на целый класс дефектов: она ловит вставку и удаление
// значения, но НЕ ловит перестановку — а перестановка здесь не косметика.
// `kRoomDeclarers`/`kGenerators`/`kRuleDeclarers` в `game/floor_gen.cpp`
// раздают работу МОДУЛЯМ ЭТАЖЕЙ по индексу `FloorKind`: переставь два значения
// в энуме, и падик начнёт генерировать хрущи, пройдя оба `static_assert`'а на
// длину и весь зелёный `ctest`. Это прямое нарушение CANON S11 («этажи —
// изолированные модули»), которое нельзя увидеть глазами в дифе энума.
//
// КАК ЭТО ЛЕЧИТСЯ
// ---------------
// Структурно, а не дисциплиной: **каждая строка несёт свой энум КОЛОНКОЙ**, и
// таблица объявляет `static_assert(rows_in_enum_order(...))`. Съехавшая таблица
// перестаёт СОБИРАТЬСЯ, а не мискеится в рантайме.
//
// Ключ в КОММЕНТАРИИ ключом не является, и это не придирка — это найденный в
// дереве случай: `kMobLootTable@src/game/loot_table.cpp` нумерует строки
// комментариями вида `/*  0 Sborka */`. Комментарий не участвует в сборке,
// значит он документация о намерении, а не свидетель. Такой таблице сперва
// нужна колонка, и только потом этот предикат.
//
// ЦЕНА ВКЛЮЧЕНИЯ — O(1): один `<cstddef>` и одна `constexpr`-функция без тел,
// зависящих от капов мира.
#pragma once
#include <cstddef>

namespace giga {

// rows_in_enum_order(rows, &Row::key) — i-я строка обязана нести значение i.
//
// Шаблон по `Enum`, а не по `int`: приведение делает `Enum(i)`, поэтому
// подставить таблицу с чужим энумом в колонке не получится — типы не сойдутся,
// и это второй, бесплатный уровень защиты поверх порядка.
template <class Row, std::size_t N, class Enum>
constexpr bool rows_in_enum_order(const Row (&rows)[N], Enum Row::*key) {
    for (std::size_t i = 0; i < N; ++i)
        if (rows[i].*key != Enum(i)) return false;
    return true;
}

// ОДНА СТРОКА НА ТАБЛИЦУ вместо двух руками. Утверждает ОБА закона —
// население и порядок, — потому что порознь они разъезжаются: длину правят,
// про порядок забывают (ровно так в дереве и вышло — 14 длин против 0 порядков).
//
// Сообщение называет, ЧТО сломается, а не только «order mismatch»: красный
// `static_assert` без этого заставляет следующего агента искать смысл руками.
#define GIGA_TABLE_BY_ENUM(TABLE, KEY, COUNT_EXPR)                             \
    static_assert(sizeof(TABLE) / sizeof((TABLE)[0])                           \
                      == static_cast<std::size_t>(COUNT_EXPR),                 \
                  #TABLE ": одна строка на значение энума — население "        \
                         "таблицы и энума разъехалось (вставили или удалили "  \
                         "значение, а таблицу не тронули).");                  \
    static_assert(::giga::rows_in_enum_order(TABLE, KEY),                      \
                  #TABLE ": строки обязаны стоять В ПОРЯДКЕ энума. Проверка "  \
                         "длины этого не ловит, а таблица индексируется "      \
                         "значением: при перестановке она начинает отвечать "  \
                         "на ЧУЖОЙ вопрос, пройдя и сборку, и ctest. "         \
                         "Поправь порядок строк, а не это утверждение.");      \
    static_assert(true, "") /* макрос требует ';' на месте вызова */

} // namespace giga
