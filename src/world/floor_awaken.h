// ОБХОД РОЖДЕНИЯ ЭТАЖА — один проход по объёму на все вопросы сразу.
//
// Почему он один. Вход на этаж обходил все 2 097 152 клетки ЧЕТЫРЕ раза, и
// каждый раз разрешал ту же страницу и крутил тот же цикл по 512 атомам:
// medium_revive (агрегаты сред), rebuild_emitter_field (излучатели),
// upload_all/classify (класс клетки зеркалу), collect_mobile_support_cells
// (опора для судьи). Замер 2026-09-23 на восстановленном этаже 0:
//
//     932 057 страниц  -> 400 + 340 + 310 + 202 = 1252 мс
//   1 539 952 страницы -> 803 + 434 + 491 + 287 = 2015 мс
//
// Отношение страниц 1.65, отношение цены 1.61: цена входа ЛИНЕЙНА по числу
// страниц и ничем другим не управляется. Разрешать страницу четырежды — это
// и есть дефект «четыре системы отвечают на один вопрос» (S11).
//
// Закон владельца 2026-09-23 дословно: «раз всё равно обходит все клетки —
// оптимизировать систему, чтобы этот прогон всё вмещал в себя универсально».
//
// ЧТО ОН ДЕЛАЕТ НА КЛЕТКЕ (страница разрешается РОВНО ОДИН РАЗ):
//   * агрегаты сред — medium_level и medium_mobile, обоими medium_digest_*
//     ([world/medium.h]), тем же разбором, что зовёт обратный шов: уровень и
//     подвижность не могут разъехаться, они выходят из одного прохода;
//   * нормализацию представления — однородная страница схлопывается в тип
//     (CANON S16.9). Это НЕ оптимизация, а восстановление инварианта
//     «страница существует ⟺ клетка неоднородна»: фронтир и генераторы родили
//     её без изменения содержимого, и она уезжала в файл этажа навсегда.
//
// ВЕТКИ RESTORE/GENERATE У НЕГО НЕТ — этаж родился, вопрос к нему один и тот
// же. Прежний medium_revive жил только в restore-ветке (генераторы считали
// агрегат сами), и эта асимметрия была ровно тем швом, где терялся закон.
//
// Параллельность — по срезам z, контракт тот же, что у [world/walk_bits.h]:
// срез это kMacroDim^2 = 16 384 клетки, кратно 64, значит ни одно слово
// битсета не делится между воркерами, а записи агрегатов идут по своему ci.
// Схлопывание страниц СЕРИАЛЬНО после обхода: оно трогает свободный список
// SubField, общий на весь этаж.
