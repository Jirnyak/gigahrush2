// --- АУДИТ ИНВАРИАНТА СТРАНИЦЫ (CANON S16.9) -------------------------------
// «Страница существует ⟺ клетка неоднородна» — и до 2026-09-30 это утверждение
// проверялось РОВНО НА ЧЕТЫРЁХ клетках, собранных руками
// ([tests/suite_saveload.inl] awaken_is_the_one_law). Этот аудит спрашивает то
// же самое у всех kMacroCells = 2 097 152 клеток и у самого пула.
//
// ЗАЧЕМ ИМЕННО ТАКОЙ ОРАКУЛ. Течь страниц (§76.5: ~1000 страниц/с в живой
// сессии владельца, монотонно, счётчик зеркала 89 063 -> 132 109 за 45 с)
// РОДИЛАСЬ В CPU-КОДЕ — её посадил open_frontier, раскрывая округу радиусом 6
// впереди материи ([render/gpu_medium_pass.cpp]). Значит она поймалась бы БЕЗ
// GPU, если бы такой обход существовал. Он не существовал, и это главная
// причина, по которой течь жила незамеченной: пин на ЧИСЛО страниц её бы не
// увидел (число законно разное на разных этажах), а производный оракул видит.
//
// Поэтому здесь НЕТ ни одного пина. Оба нарушения — тождества, верные на любом
// содержимом любого этажа:
//   uniform_paged == 0  — страница при однородной клетке (её обязан был
//                         схлопнуть settle_sub_page). Это ТЕЧЬ: такая страница
//                         уезжает в файл этажа навсегда и оплачивается ценой
//                         следующего входа;
//   orphan_slots  == 0  — слот занят пулом, но на него не смотрит ни одна
//                         клетка и он не лежит в свободном списке. Это течь
//                         второго рода: слот потерян до перезагрузки этажа.
//
// Считается по полю материалов (kSubMaterialName) — тому, которым живёт
// мир-автомат. Поле пятен ([world/stain.h]) сегодня течёт своим способом
// (ensure_page без парного освобождения, ни drop_page, ни collapse нигде) и
// ПОД АУДИТ НЕ ВЗЯТО СОЗНАТЕЛЬНО: включать его сюда значило бы завести гейт,
// красный с первой минуты, и он был бы немедленно выключен. Долг записан
// отдельно.
struct PageAuditStats {
    std::size_t paged_cells = 0;   // клеток, у которых есть страница
    std::size_t pages_in_use = 0;  // слотов занято по учёту пула
    // Верхняя вода пула (page_count — ВЕСЬ вектор, с дырами). После рождения
    // этажа обязана равняться pages_in_use: компакт floor_awaken пересадил
    // занятые в дыры и отдал хвост — иначе зеркало лило бы и дыры тоже
    // (floor 6: 649k схлопнутых слотов ехали бы в каждую заливку).
    std::size_t page_slots = 0;
    std::size_t uniform_paged = 0; // НАРУШЕНИЕ: страница при однородной клетке
    std::size_t orphan_slots = 0;  // НАРУШЕНИЕ: слот занят, клетки на него нет

    // Одно число для CHECK'а — сумма нарушений. Ноль на честном дереве.
    std::size_t violations() const { return uniform_paged + orphan_slots; }
};

PageAuditStats audit_sub_pages(const World& w);

// --- АУДИТ ЗАКОНА МАСКИ (CANON S16.10) -------------------------------------
// Перепись CPU-канона одним проходом: что в мире несёт бит «твёрдое и
// улеглось», а что нет. Зачем: бит над воздухом — стена, которой нет, а
// найти её глазами нельзя. Прибор поймал два дефекта в первый же вечер
// (2026-11-12): автомат, шагавший по зеркалу покинутого этажа, переносил его
// байты в новый мир (9–15 тыс. битов над воздухом за две поездки, с фронтиром
// рождения — 46–72 тыс.), а первая форма закона ставила бит неподвижной
// материи (160 тыс. атомов). Печатается при `--mirror-verify`.
struct MaskAuditStats {
    std::size_t loose = 0;         // атомов подвижной твёрдой материи
    std::size_t loose_unlaid = 0;  // из них без бита: летит или не улеглось
    // НАРУШЕНИЕ: бит над не-твёрдым (воздух, жидкость, газ) — в страничной
    // клетке по материалу атома, в бесстраничной по её типу.
    std::size_t ghost_bits = 0;
    std::size_t ghost_cells = 0;
    // Неподвижная материя без бита. Не нарушение само по себе (так писатель
    // статики держит материю без коллизии), но генератор сегодня оставляет
    // такие атомы сотнями тысяч, а сейв стирает их на входе как фантомы.
    std::size_t static_unmasked = 0;
};

MaskAuditStats audit_mask_law(const World& w);

// НОРМАЛИЗАЦИЯ ПЕРЕД СЕРИАЛИЗАЦИЕЙ — инвариант S16.9 на ВЫХОДЕ с этажа.
//
// Рождение этажа схлопывает однородные страницы (floor_awaken выше), но
// фронтир сред раскрывает их ЗА МИНУТЫ ЖИЗНИ, не меняя содержимого (§76.5),
// живой settle их не душит, и до 2026-11-08 файл этажа вёз их НАВСЕГДА:
// floor 0 после визитов — 925600 страниц, файл 156 МБ, рестор в воркере
// 2.2 с, пул 904 МиБ. Схлопывание той же парой (collapse + тип в клетку),
// что у рождения, одним проходом.
//
// Зовётся ФОНОВЫМ КОДЕКОМ на tmp-мире, которым тот владеет целиком
// ([app] write_floor_file_async). ЖИВОЙ мир этим трогать НЕЛЬЗЯ: зеркало
// держит GPU-индекс страниц по слотам пула, и молчаливый drop_page показал
// бы чужой материал до следующей полной заливки. Возвращает число
// схлопнутых — кодек печатает его вслух.
std::size_t settle_uniform_pages(World& w);

// ФРОНТИР СРЕД — страницы ВПЕРЁД материи (закон владельца 2026-08-27: «в игре
// ничего не должно зависеть от кадра»). Материя автомата входит только в
// клетку со страницей, поэтому страницы обязаны существовать ДО её прихода —
// иначе срабатывает гейт «нераскрытая клетка», и физика перестаёт быть чистой
// функцией номера подтика (пин: test_cadence_equivalence).
//
// РАДИУС — вывод (S11), от полного круга доставки страницы: GPU-факт «клетка
// жива» едет в CPU kRbRegions+1 кадра (кольцо шва), материализованная страница
// едет назад флешем ещё кадр — kRbRegions+2 = 5 кадров; кадр несёт до
// kMediumMaxPerFrame = 8 подтиков (кап догона), Марголус двигает не быстрее
// 1 субвокселя/подтик => клетка пересекается не быстрее kSubDim = 8 подтиков.
// R = (kRbRegions+2)*8/8 = 5, плюс 1 запаса: равенство на потолке — не запас.
// Сам kRbRegions живёт в рендере, ядро его не видит: равенство стережёт
// static_assert в [render/gpu_medium_pass.cpp].
inline constexpr int kFrontierRadius = 6;

// Полномасочная клетка СТАТИЧНОЙ материи: будить нечего и страница не
// нужна — входа материи нет. Прежний фильтр «full() = статика» писался ДО
// подвижного рабла: полномасочный рыхлый двойник (rubble, flow 1.0) подвижен
// ЦЕЛИКОМ, и фильтр делал такие клетки невидимыми всем будильникам (корень В2
// висяков, medium-stability.md). Предикат — ТОЛЬКО маска + тип (канон CPU):
// чтение paged() здесь дивергировало каденс (страницы материализуются по
// таймингам КАДРА — пин test_cadence_equivalence поймал с первого прогона).
bool cell_full_static(const World& w, std::uint32_t ci);

// Раскрыть (материализовать) страницы куба радиуса kFrontierRadius вокруг
// клетки — БЕЗ пробуждения: пустые страницы в живой список не входят, материя
// будит цели сама. Дедуп бесплатен: материализация делает клетку paged,
// повторный сосед отсеивается первой проверкой; полную статику не трогаем.
// Один закон на оба вызывающих: рождение этажа (ниже) и писатель/шов живого
// мира ([render/gpu_medium_pass.cpp] open_frontier). `opened` — куда дописать
// раскрытые клетки (долг зеркала у живого мира); может быть nullptr.
// Возвращает число раскрытых страниц.
std::size_t open_frontier_cube(World& w, std::uint32_t ci,
                               std::vector<std::uint32_t>* opened);

struct FloorFrontierStats {
    std::size_t sources = 0; // клеток с подвижной материей (не полная статика)
    std::size_t pages = 0;   // страниц раскрыто
    double ms = 0.0;
};

// ФРОНТИР РОЖДЕНИЯ ЭТАЖА (лифт-лимб, шаг 2). Будильник этажа будит все клетки
// с подвижной материей, и писатель раскрывал округу каждой на ГЛАВНОМ ПОТОКЕ в
// кадре входа: 78 893 страницы за 118.5 мс из 465 мс кадра (замер 2026-11-12,
// `--lift 1`). Это чистая работа над миром этажа, которым до свопа владеет
// воркер пребилда, — и здесь она делается им же, тем же законом
// (open_frontier_cube) и по тем же источникам в том же порядке (возрастание
// индекса клетки). Главному потоку остаются пробы: страниц он раскрывает ноль.
//
// Зовётся ПОСЛЕ floor_awaken: тот схлопывает однородные страницы, и раскрытое
// до него он бы тут же снёс. Раскрытые страницы воздуха однородны — это
// НАЗВАННАЯ оговорка S16.9 (фронтир — представление, зависящее от того, где
// лежит материя); аудит `uniform_paged == 0` верен между floor_awaken и этим
// вызовом. Умирают они там же, где и раньше: на выходе с этажа
// (settle_uniform_pages) и на следующем рождении.
FloorFrontierStats floor_open_frontier(World& w);

