// ЩИТ — персистентная маска защищённых 3D-областей этажа.
//
// Решение владельца 2026-08-27: лифт — ключевая механика, его нельзя
// разрушить. Материального закона (kHardnessUnbreakable) мало: владельцу
// нужна ОБЛАСТЬ — щит поверх любых материалов, чтобы модуль этажа мог
// объявить «этот объём неприкосновенен», не перекрашивая геометрию.
//
// ЗАКОН: клетку под щитом не меняет НИКАКОЙ писатель геометрии — карв
// (remove_key — единственная точка выреза атома), детач-конверсия в
// rubble, и БУДУЩИЙ САМОСБОР (его гейт — эта же маска; потребитель придёт
// со своим эпиком). Щит — про ГЕОМЕТРИЮ: среды, свет и тела живут поверх
// свободно (вода в шахте лифта течёт — это не разрушение).
//
// НЕ в снимке ревизита: маска — чистая функция модуля (kind, number,
// seed), перештамповывается на каждом входе ОБЕИМИ ветками (generate и
// restore) — как законы этажа, не как сохранённые байты.
//
// Плотный битсет по kMacroCells (256 КиБ на World) — изотропный, O(1)
// проверка в горячем пути карва.
#pragma once

#include <algorithm>
#include <cstdint>
#include <vector>

#include "world/types.h" // kMacroCells

namespace giga {

struct ProtectMask {
    std::vector<std::uint64_t> bits =
        std::vector<std::uint64_t>(kMacroCells / 64, 0ull);

    void clear_all() { std::fill(bits.begin(), bits.end(), 0ull); }
    void set(std::size_t ci) { bits[ci >> 6] |= 1ull << (ci & 63u); }
    bool test(std::size_t ci) const {
        return ((bits[ci >> 6] >> (ci & 63u)) & 1u) != 0u;
    }
};

} // namespace giga
