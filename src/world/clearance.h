// Гранный клиренс — ОДИН закон проходимости, агностичный к размеру (S2 «волна
// 3» / occupancy; закрывает последнее большое гнездо §60 [problems.md]).
//
// Вопрос «пролезет ли ЭТО?» — вопрос о ПЕРЕХОДЕ между двумя клетками, а не о
// клетке самой по себе. Клеточный предикат `!mask.full()` — планка 1 атом из
// 512: на лепленом этаже полных клеток 0.4%, и нав прокладывал маршруты сквозь
// стены, а запах тёк сквозь глухую кладку ([world/nav.cpp] бывший cell_open,
// [sim/diffusion.cpp] его дубль — оба лечатся здесь). Канон S2 дословно:
// клетка законна как ступень иерархии, но ОТВЕЧАТЬ на локальный вопрос обязаны
// атомы.
//
// ЗАКОН (владелец, 2026-08-26, эпик №10 — «универсальная агностичная
// проходимость от размера; жертвуем точностью ради универсальности»):
//
//   клиренс(грань A|B) = макс. s: квадрат s×s чист в
//       ( возд. проекция БЛИЖНЕЙ К ГРАНИ половины A вдоль оси перехода
//       & возд. проекция ближней половины B вдоль той же оси )
//
// и проходимость ЛЮБОГО существа/пропа — одно сравнение `клиренс >= габарит`:
// тело NPC — 4 (вывод у потребителя, [game/embody.cpp] полуширина 0.4 м);
// газу хватает одного атома — 1. Один бейк обслуживает все размеры.
//
// Почему ПОЛОВИНА глубины (kSubDim/2 = 4 слоя), а не грань и не вся клетка:
//  - слой самой грани слеп к стене в одном субвокселе от неё;
//  - сквозная проекция всей клетки запирает повороты коридоров (дальняя
//    стена угловой клетки гасит проекцию, хотя тело поворачивает, не дойдя
//    до неё);
//  - половина — единственное разбиение без дыр и перekрытий: дальняя половина
//    A — это ближняя половина ПРОТИВОПОЛОЖНОЙ грани A, т.е. каждый атом клетки
//    сторожит ровно те переходы, которые он физически загораживает. Глубина
//    окна 4+4 = 8 субвокселей = 2 м вокруг грани.
//
// Известная слепота (принята владельцем — «неточность не страшна»): хранится
// макс. КВАДРАТ, не прямоугольник — окно 4×4 (1×1 м) пропустит по предикату
// тело 4×4×7, которое в него не пролезет физически; тело упрётся и
// перепланирует. Лекарство (второй нибл прямоугольника, +2 МиБ) — по факту
// жалоб, не вперёд.
//
// O(1) на грань бит-магией: проекция половины — свёртка 4 слоёв маски в
// битмап 8×8 (u64), макс-квадрат — итерированная эрозия (<= 8 шагов по 4
// операции). Полный бейк — parallel_for по слоям; патч карва — клетка + 3
// соседа с минус-стороны, 6 гранных значений, без пересканов окрестности.
#pragma once

#include <cstdint>
#include <vector>

#include "world/types.h" // kMacroDim, kMacroCells, macro_index, wrap_macro

namespace giga {

struct SubMask;  // world/macro_grid.h — источник правды, 8³ атомов клетки
class MacroGrid;

// Сторона наибольшего сплошного квадрата s×s в битмапе 8×8 (бит = u + v*8),
// 0..8. Итерированная эрозия: b &= сдвиги на (1,0),(0,1),(1,1) с гашением
// заворота колонок; число непустых итераций и есть сторона. Публична ради
// тестов-пинов — потребители зовут face_clearance.
int max_square(std::uint64_t bitmap);

// Клиренс перехода через общую грань: `a` — клетка с МЛАДШЕЙ стороны оси
// (переход через её +axis-грань в `b`, соседа сверху по оси). Оси 0/1/2 =
// x/y/z, все три равноправны (S1) — Z дешевле только потому, что это ось
// упаковки слов маски. Ответ 0 (глухо) .. 8 (обе половины — воздух).
std::uint8_t face_clearance(const SubMask& a, const SubMask& b, int axis);

// Тот же закон по координатам: клиренс +axis-грани клетки (x,y,z) с её
// соседом сверху по оси (заворот внутри). Для потребителей, которым нужна
// ОДНА грань — например, двере-осведомлённый дренаж карва в game, который
// обязан пропускать грани, упирающиеся в клетку двери (премиса all-open,
// [game/rebake.h] patch_carved_cells).
std::uint8_t face_clearance_at(const MacroGrid& grid, int x, int y, int z,
                               int axis);

// Поле клиренса этажа: 3 нибла на клетку — её +x/+y/+z грани (минус-грань
// клетки — это плюс-грань соседа, второй раз не хранится). u16 на клетку =
// 4 МиБ на этаж; снапшот для фонового ребейка — копия вектора.
struct ClearanceField {
    std::vector<std::uint16_t> vals; // [macro_index] = c_x | c_y<<4 | c_z<<8

    bool built() const { return !vals.empty(); }

    // Клиренс грани, через которую уходит шаг из (x,y,z) в направлении `dir`
    // 0..5 в ПОРЯДКЕ НАВА -x,+x,-y,+y,-z,+z ([world/nav.h] kNavDir — тот же
    // порядок держат BFS и решётка). Минус-направление читает нибл соседа.
    std::uint8_t at(int x, int y, int z, int dir) const {
        const int axis = dir >> 1;
        if ((dir & 1) == 0) { // -axis: плюс-грань соседа снизу по оси
            if (axis == 0) x -= 1;
            else if (axis == 1) y -= 1;
            else z -= 1;
        }
        const std::size_t i =
            macro_index(wrap_macro(x), wrap_macro(y), wrap_macro(z));
        return static_cast<std::uint8_t>((vals[i] >> (4 * axis)) & 0xFu);
    }

    // Полный бейк с живого грида — при загрузке этажа и в фоновом ребейке
    // (свап по готовности, S9). Параллелен по z-слоям, бит-идентичен при
    // любом числе потоков (каждая клетка пишет только свой u16).
    void build(const MacroGrid& grid);

    // O(1)-патч одной клетки после карва/записи автомата: пересчитывает её
    // 3 нибла и плюс-нибл трёх соседей с минус-стороны — все 6 граней, чью
    // половину эта маска сторожит. Обязан жить в ОБОИХ путях (бейк и патч
    // карва) — закон дрейфа предикатов [world/walk_bits.h].
    void patch(const MacroGrid& grid, int x, int y, int z);

    // Запись ОДНОЙ +axis-грани клетки — для дренажей с политикой (двери):
    // game сам решает, какие грани пересчитывать, и кладёт сюда результат
    // face_clearance_at. Координаты заворачиваются.
    void set_face(int x, int y, int z, int axis, std::uint8_t v) {
        std::uint16_t& w =
            vals[macro_index(wrap_macro(x), wrap_macro(y), wrap_macro(z))];
        w = static_cast<std::uint16_t>(
            (w & ~(0xFu << (4 * axis))) |
            (static_cast<std::uint16_t>(v & 0xFu) << (4 * axis)));
    }
};

} // namespace giga
