// Студийная заставка — «TENEVIK GAMES» собирается из клеток-пикселей и
// физически перетекает в титул «ГИГАХРУЩ 2» над главным меню.
//
// ПОРТ МЕХАНИКИ РЕФА (starcluster shell.cpp), не мотивов: первая версия
// повторяла идею экспоненциальным лерпом и была отвергнута владельцем
// («всратое, хуже рефа»). Разрыв оказался в трёх вещах, все три здесь:
//   * SUPER×SUPER клеток на пиксель глифа — буква читается плотным клеточным
//     полем, а не редкой сыпью из 1 клетки на пиксель;
//   * ЛЕНТА: разлёт симулируется ВПЕРЁД при инициализации (случайное
//     блуждание + коллизии клетка-об-клетку), на экран попадает только его
//     ОТМОТКА — сборка едет по органичным траекториям, не по прямым;
//   * курсор — игрушка: клетки можно вести, толкать и разбивать щелчком;
//     сбитая клетка живёт инерцией и отскоками, потом снова ищет свой слот.
//
// Палитра — решение владельца после плейтеста: КРАСНЫЙ — доминанта (слово и
// титул), оранжевый — второе слово, зелёный остаётся интерфейсу. Цвет держит
// СЛОВО, не клетка: конфетти из случайных цветов читалось шумом.
//
// Самодостаточно: ноль игровых данных, рисует в ImDrawList, состояние своё.
// Хозяин фаз — UiShell ([ui_shell.h]): Intro рисует сборку логотипа,
// Menu — титул; переход intro->menu дёргает retarget_title().
#pragma once

#include <cstdint>
#include <vector>

struct ImDrawList;

namespace giga {

struct IntroFx {
    struct Cell {
        float x, y;    // текущее
        float hx, hy;  // дом (слот глифа или точка дрейфа)
        float vx, vy;
        float wob;     // фаза покачивания дрейфа
        float rate;    // индивидуальный темп отмотки, 0.65..1.35
        float cur;     // курсор по ленте (кадры); <=0 — сошла с ленты
        std::uint8_t word;   // 0 верхнее слово/титул, 1 нижнее, 2 дрейф фона
        std::uint8_t freed;  // 1 = физическая: инерция, отскоки, тяга домой
    };

    std::vector<Cell> cells;
    std::vector<short> tape;  // [кадр][клетка] -> (x, y), пишется при build
    int tapeSteps = 0;
    float phaseTime = 0.0f;
    float stubborn = 0.0f;   // «мешать можно, победить нельзя»
    float drawPx = 8.0f;     // текущий размер клетки (плавно едет к target)
    float targetPx = 8.0f;
    bool builtLogo = false;
    bool titleMode = false;
    std::uint32_t seed = 0x7E9E71Cu;
    // Прошлый кадр мыши — для скорости курсора (ведение передаёт импульс).
    float pmx = -1000.0f, pmy = -1000.0f;
    // Размер экрана прошлого кадра: ресайз (фуллскрин) пере-раскладывает
    // слоты, иначе слово остаётся у СТАРОГО центра и уезжает влево.
    float lastW = 0.0f, lastH = 0.0f;

    // Переиспользуемые буферы коллизий (сетка соседей).
    std::vector<int> gridHead, gridNext;
    std::vector<std::uint8_t> hot;

    // Разложить «TENEVIK / GAMES», мгновенно прокрутить разлёт в ленту и
    // поставить поле в её последний кадр. Зовётся лениво из step_draw().
    void build_logo(float w, float h);

    // Тем же клеткам — слоты титула «ГИГАХРУЩ 2» (крупно, 0.66 ширины);
    // лишние — в дрейф фона. Зовётся один раз на переходе Intro -> Menu.
    void retarget_title(float w, float h);

    // Шаг физики + отрисовка. Возвращает true, когда слово собралось —
    // Intro может показывать подпись и подсказку.
    bool step_draw(ImDrawList* dl, float w, float h, float dt);
};

} // namespace giga
