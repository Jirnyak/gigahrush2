// Раскладка стерео-кадра — чистая арифметика, без Vulkan и без окна.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Режим Side-by-Side ломается ровно в трёх местах, и все
// три — целочисленная арифметика, которую на глаз не проверить: полоса в один
// пиксель по шву, съехавший на пиксель полурезный свет (полосатая тень только
// у правого глаза) и объект, пропавший у одного глаза из-за отбора по чужому
// фрустуму. Арифметика живёт здесь, компилируется в giga_core и пинится
// world_test'ом — тот же приём, что у геймпада ([game/gamepad.h]).
//
// ЭТО НЕ VR. Здесь нет и не будет трекинга головы, OpenXR, дисторсии линз и
// timewarp; оба глаза делят ОДНУ матрицу проекции, а шлему нужен свой
// асимметричный фрустум на глаз. Это 3D-режим на плоском экране
// ([markoaudit/plans/marko-vr-pick.md] §3б).
#pragma once

namespace giga::gpu {

// Прямоугольник кадра в пикселях. Свой, а не VkRect2D: этот заголовок обязан
// собираться там, где Vulkan'а нет.
struct ScreenRect {
    int x = 0;
    int y = 0;
    int w = 0;
    int h = 0;
};

// Сколько глаз рисует кадр. Два — потому что их два; константа названа, чтобы
// «2» не расползлось по циклам как безымянный литерал.
inline constexpr int kStereoEyes = 2;

// Прямоугольник глаза `eye` в кадре `width x height`.
//
// ВЫВОД ГРАНИЦЫ: шов ровно посередине, `width / 2`. При НЕЧЁТНОЙ ширине лишний
// столбец достаётся правому глазу — не потому что он важнее, а потому что
// разбиение обязано быть РАЗБИЕНИЕМ: без зазора (чёрная полоса по шву) и без
// нахлёста (правый глаз затирает столбец левого). Любое «поделим пополам и
// округлим оба» даёт одно из двух.
inline ScreenRect stereo_eye_rect(int width, int height, int eye, int eyeCount) {
    if (eyeCount < kStereoEyes) return ScreenRect{0, 0, width, height};
    const int mid = width / 2;
    return eye == 0 ? ScreenRect{0, 0, mid, height}
                    : ScreenRect{mid, 0, width - mid, height};
}

// Прямоугольник того же глаза в ПОЛУРЕЗНОЙ световой цели.
//
// ВЫВОД: полный кадр читает свет как `floor(gl_FragCoord.xy * 0.5)`
// ([shaders/raymarch.frag]), а цель имеет размер `(N + 1) / 2` по каждой оси.
// Значит прямоугольник глаза обязан покрыть образ ВСЕХ своих фрагментов при
// этом отображении: x пробегает [x0, x1) -> floor(x/2) пробегает
// [x0/2, (x1-1)/2]. Отсюда полуинтервал [x0/2, (x1+1)/2). Он же гарантирует,
// что два глаза замостят цель без зазора — тот самый столбец, из-за которого
// иначе у одного глаза свет съезжает на пиксель.
//
// Целевая ЦЕЛИКОМ не пересоздаётся под глаз: она остаётся полукадром, и оба
// глаза пишут каждый в свою половину. Ровно поэтому шейдер полного кадра
// остаётся неизменным — его `gl_FragCoord * 0.5` уже попадает куда надо.
inline ScreenRect half_res_rect(ScreenRect full) {
    const int x0 = full.x / 2;
    const int y0 = full.y / 2;
    const int x1 = (full.x + full.w + 1) / 2;
    const int y1 = (full.y + full.h + 1) / 2;
    return ScreenRect{x0, y0, x1 - x0, y1 - y0};
}

// Насколько отодвинуть назад по взгляду камеру ОТБОРА, чтобы её фрустум
// накрыл фрустумы ОБОИХ глаз. Метры.
//
// ВЫВОД. Глаза — это тот же фрустум, сдвинутый на ±ipd/2 вбок. Апекс, отодвинутый
// назад на d, на расстоянии z имеет полуширину (z + d)·t, где t = tg(fovX/2);
// глазу нужно z·t + ipd/2. Условие накрытия: (z + d)·t >= z·t + ipd/2, то есть
// **d >= ipd / (2·t)** — от z не зависит, одно число на весь кадр. По вертикали
// отодвинутый фрустум строго шире, ближняя плоскость уезжает ближе — обе
// стороны в запас.
//
// `projM0` — элемент [0][0] матрицы проекции, а он и есть 1/tg(fovX/2)
// ([core/math.h] mat4_perspective: m[0] = (1/tg(fovY/2)) / aspect). Берём его
// из САМОЙ матрицы, а не пересчитываем из fov и аспекта: так формула не может
// разойтись с проекцией, которой рисуют.
//
// Это честная альтернатива «в стерео отбор выключить целиком»: выключенный
// отбор рисует ВСЕ пропы обоим глазам и стоит дороже самого стерео.
inline float stereo_cull_pullback(float ipd, float projM0) {
    const float halfIpd = ipd * 0.5f;
    return halfIpd > 0.0f && projM0 > 0.0f ? halfIpd * projM0 : 0.0f;
}

} // namespace giga::gpu
