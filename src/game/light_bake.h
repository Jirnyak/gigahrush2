// light_bake.h — статические эмиттеры из СВЕТОМАТЕРИАЛОВ ([ddalight.md]).
//
// Любой воксель, чей материал несёт light_radius_mm в data/materials.csv,
// излучает. Бейк при постройке этажа сканирует сетку, КЛАСТЕРИЗУЕТ соседние
// светоячейки одного материала (полоса неона из 20 ячеек = один эмиттер, а не
// двадцать) и отдаёт список для collect_scene_lights. Так «нарисованное
// светом» — вывеска, узор, вылепленная вокселями лампа — становится настоящим
// источником: с тенями, гало в дымке и смертью от carve (перезапуск бейка —
// следующий инкремент; v1 статичен до перестройки этажа).
//
// Кластер — 6-связность ПО ТОРУ (все три оси, врап на битовом И, как везде);
// центроид копится wrap-дельтами от затравки, радиус эмиттера = табличный
// радиус материала + полудиагональ кластера (выведено, не подобрано).
#pragma once

#include <vector>

#include "core/math.h"

namespace giga {
class World;
}

namespace giga::game {

struct BakedLight {
    vec3  pos{0.0f, 0.0f, 0.0f};
    float radiusM = 0.0f;
    vec3  color{1.0f, 1.0f, 1.0f}; // = альбедо материала: неон светит как покрашен
    float intensity = 0.0f;
};

// Скан + кластеризация. Детерминирован от геометрии; зовётся при постройке
// этажа рядом с refresh_floor_props ([main.cpp]).
std::vector<BakedLight> bake_material_lights(const World& world);

} // namespace giga::game
