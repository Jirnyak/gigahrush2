// light_bake.h — статические эмиттеры из СВЕТОМАТЕРИАЛОВ ([ddalight.md]).
//
// Любой воксель, чей материал несёт light_radius_mm в data/materials.csv,
// излучает. Светящаяся ЯЧЕЙКА — это ячейка со светящимися АТОМАМИ (закон двух
// масштабов, CANON S2): однородная ячейка отвечает типом, паженная — сканом
// своей субвоксельной страницы.
//
// EmitterField — постоянное поле светоячеек этажа. Полный субвоксельный скан
// 128³ (сотни мс) платится ОДИН раз, при постройке этажа; карв и кисть латают
// поле только по своим dirtyCells (O(задетых ячеек), микросекунды) — фриз на
// каждом разрушении неона убит этим разделением
// ([markoaudit/plans/neon-topology.md] §4). Патч заодно СУБВОКСЕЛЬНО честен:
// старая проверка «задел ли карв светоматериал» спрашивала только тип ячейки
// и не видела неон, нарисованный атомами в чужой ячейке.
//
// Кластер — 6-связность ПО ТОРУ (все три оси, врап на битовом И, как везде);
// центроид копится wrap-дельтами от затравки, радиус эмиттера = табличный
// радиус материала + полудиагональ кластера (выведено, не подобрано).
#pragma once

#include <cstdint>
#include <vector>

#include "core/math.h"
#include "world/macro_grid.h"

namespace giga {
class World;
}

namespace giga::game {

struct BakedLight {
    vec3  pos{0.0f, 0.0f, 0.0f};
    float radiusM = 0.0f;
    vec3  color{1.0f, 1.0f, 1.0f}; // = альбедо материала: неон светит как покрашен
    float intensity = 0.0f;
};

// Поле светоячеек: mat[i] — светящийся материал ячейки i (0 = не светит),
// cells — отсортированные плоские индексы светоячеек (их мало; кластеризация
// обходит только их, а не 128³).
struct EmitterField {
    std::vector<CellType> mat;
    std::vector<std::uint32_t> cells;
};

// Полный субвоксельный скан этажа. Зовётся при постройке этажа рядом с
// refresh_floor_props ([main.cpp]) — и больше НИГДЕ: в кадре поле латается.
void rebuild_emitter_field(const World& world, EmitterField& f);

// Перепроверить только ячейки dirty (плоские macro-индексы, формат dirtyCells
// карва). Возвращает true, если поле изменилось — сигнал вызывающему перепечь
// кластеры и статик-таблицу. Зовётся ПОСЛЕ мутации мира: сравнение идёт со
// снимком поля, «было светило — стало воздух» видно без проверки до карва.
bool patch_emitter_field(const World& world, EmitterField& f,
                         const std::uint32_t* dirty, std::size_t n);

// Кластеризация поля. Детерминирована от геометрии: обход cells по
// возрастанию индекса — тот же порядок, что у полного скана z/y/x.
std::vector<BakedLight> bake_material_lights(const EmitterField& f);

} // namespace giga::game
