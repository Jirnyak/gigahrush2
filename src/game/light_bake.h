// light_bake.h — статические эмиттеры из СВЕТОМАТЕРИАЛОВ ([ddalight.md]).
//
// Любой воксель, чей материал несёт light_radius_mm в data/materials.csv,
// излучает. Светящийся АТОМ — это субвоксель, который СУЩЕСТВУЕТ (бит маски
// присутствия) и чей материал светит: карв чистит только маску ([destruct.cpp]
// remove_key), материал страницы живёт до опустения клетки — бейк, спрашивающий
// одни материалы, считал выбитые атомы светящимися (корень «свет остался»,
// [markoaudit/plans/neon-topology.md]).
//
// ИДЕНТИЧНОСТЬ КЛАСТЕРА — ИЗ СВЯЗНОСТИ, НЕ ИЗ ПОЗИЦИИ (решение владельца
// 2026-08-24, дословно в neon-topology.md): кластер = связная 6-компонента
// светящихся АТОМОВ (не клеток), его id живёт в EmitterClusters и переживает
// изменение формы. Разрушение = уменьшение (та же компонента похудела — тот же
// id); разделение — часть с самым младшим выжившим атомом наследует id, прочие
// получают новые; слияние — выживает младший id. Центроид/радиус — производные
// для рендера, никогда не признак «та же это лампа или другая».
//
// EmitterField — постоянное поле светоячеек этажа. Полный субвоксельный скан
// 128³ (сотни мс) платится ОДИН раз, при постройке этажа; карв и спавн неона
// латают поле только по своим dirtyCells (O(задетых ячеек)) — фриз на каждом
// разрушении неона убит этим разделением (§4 плана). emitMask хранит светящиеся
// атомы поклеточно, поэтому патч видит и выбитый ОДИН атом.
//
// Связность — 6-соседство ПО ТОРУ (все три оси, врап на битовом И, как везде);
// центроид копится wrap-дельтами от затравки, радиус эмиттера = табличный
// радиус материала + полудиагональ кластера (выведено, не подобрано).
#pragma once

#include <cstdint>
#include <utility>
#include <vector>

#include "core/math.h"
#include "world/macro_grid.h"

namespace giga {
class World;
}

namespace giga::game {

struct BakedLight {
    vec3  pos{0.0f, 0.0f, 0.0f};
    float radiusM = 0.0f;
    vec3  color{1.0f, 1.0f, 1.0f}; // = альбедо материала: неон светит как покрашен
    float intensity = 0.0f;
    // Устойчивый id компоненты (см. EmitterClusters): по нему статик-таблица
    // узнаёт «ту же лампу» между пересборками — позиция в матчинге не участвует.
    std::uint32_t id = 0;
};

// Поле светоячеек: mat[i] — светящийся материал ячейки i (0 = не светит),
// cells — отсортированные плоские индексы светоячеек, emitMask — параллельно
// cells: битовая маска СВЕТЯЩИХСЯ АТОМОВ ячейки (присутствие ∧ материал).
struct EmitterField {
    std::vector<CellType> mat;
    std::vector<std::uint32_t> cells;
    std::vector<SubMask> emitMask;
};

// Идентичность компонент между бейками. atomOwner — светящиеся атомы прошлого
// бейка (плоский индекс субвокселя 1024³ → id компоненты), отсортирован по
// атому: «самый младший выживший атом компоненты» — первый её атом, живой в
// новом бейке, и его компонента наследует id. Сбрасывается постройкой этажа.
struct EmitterClusters {
    std::vector<std::pair<std::uint32_t, std::uint32_t>> atomOwner;
    std::uint32_t nextId = 0;
};

// Полный субвоксельный скан этажа. Зовётся при постройке этажа рядом с
// refresh_floor_props ([main.cpp]) — и больше НИГДЕ: в кадре поле латается.
void rebuild_emitter_field(const World& world, EmitterField& f);

// Перепроверить только ячейки dirty (плоские macro-индексы, формат dirtyCells
// карва). Возвращает true, если поле изменилось — сигнал вызывающему перепечь
// кластеры и статик-таблицу. Зовётся ПОСЛЕ мутации мира: сравнение идёт со
// снимком поля (включая emitMask — выбитый одиночный атом виден), «было
// светило — стало воздух» видно без проверки до карва.
bool patch_emitter_field(const World& world, EmitterField& f,
                         const std::uint32_t* dirty, std::size_t n);

// Кластеризация поля по атомной связности + наследование id через c.
// Детерминирована от геометрии: обход ячеек по возрастанию индекса, атомов —
// по возрастанию бита.
std::vector<BakedLight> bake_material_lights(const World& world,
                                             const EmitterField& f,
                                             EmitterClusters& c);

} // namespace giga::game
