// Публикация деяния — глагол продюсера: пакует запись в шину (S19.1.1).
// `actor` может быть entt::null (среда/автоматика — деяние без дипломатии),
// `victim` — kInvalidNpc, когда жертвы нет.
void deed_publish(EventBus& bus, VerbId verb, Entity actor, NpcId victim,
                  const vec3& pos, std::uint64_t tick);

// Что сделал один проход свидетеля — наблюдения для HUD/тестов.
struct WitnessTick {
    std::uint32_t deeds = 0;     // деяний рассмотрено
    std::uint32_t witnessed = 0; // из них воспринято хотя бы кем-то
    std::uint32_t free = 0;      // занулено уместностью (комната предлагает)
    std::uint32_t changes = 0;   // сдвигов матрицы
};

// Потребитель свидетельства: за тик собрать деяния из шины, найти
// воспринявших, оценить по таблице цен, применить к матрице и репутации
// комнаты, опубликовать RelationChanged. Плюс выцветание репутации комнат
// на секундном кадансе. Образец дренажа — relations_drain_deaths (снапшот
// size() до цикла: RelationChanged падают в то же кольцо).
WitnessTick witness_step(Registry& reg, NpcPool& pool, FactionRelations& rel,
                         EventBus& bus, FloorRooms& rooms, const World& world,
                         LayerId layer, std::uint64_t tick);

