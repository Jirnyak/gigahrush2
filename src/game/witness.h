// Свидетельство (CANON S19) — поступок, УВИДЕННЫЙ кем-то, имеет цену.
//
// Одна система, четыре ступени (S19.1):
//   1. ДЕЯНИЕ — событие существующей шины (EventType::Deed): актор, глагол
//      из ЕДИНОГО словаря verbs.csv (его пятый стол), жертва (опц.), клетка.
//      Деяние не знает о последствиях.
//   2. СВИДЕТЕЛЬ — только ВОСПРИНЯВШИЙ: воплощённый агент, который ВИДЕЛ
//      (sub_march — субвоксельный луч без препятствий) или СЛЫШАЛ
//      (skeleton_audible — путь по граням скелета в радиусе слышимости
//      деяния из таблицы). Всеведения нет по построению: незамеченное
//      деяние не имеет социальной цены — идеальное преступление возможно.
//   3. ОЦЕНКА — контекст = данные (S19.2, колонки verbs.csv кодогеном):
//      базовая дельта, множитель своей территории (свидетель из фракции
//      собственника комнаты), множитель своей жертвы; уместность зануляет
//      цену ЦЕЛИКОМ (комната сама ПРЕДЛАГАЕТ глагол деяния — S12.4:
//      облегчение в сортире ноль, драка на арене ноль; вторая таксономия
//      уместности не заводится). Жертва, враждебная свидетелю, зануляет
//      цену для НЕГО: лечишь врага свидетеля — не заслуга, бьёшь — не
//      преступление.
//   4. ПОСЛЕДСТВИЯ — существующие носители, новых нет: матрица фракций
//      (одна поправка на пару строк за деяние, сколько бы свидетелей одной
//      фракции ни столпилось) + репутация комнаты (Room::rep, одна запись
//      с выцветанием — S13.6). Публикует RelationChanged, как прежний
//      потребитель смертей.
//
// ЛОКАЛИЗАЦИЯ СМЕРТЕЙ (S19.3 — расхождение, которое S19 обязан закрыть):
// relations_drain_deaths был ВСЕВИДЯЩ — убийство гнуло матрицу без единого
// свидетеля. Его логика стала строкой цены глагола «убить» (kVerbKill,
// rel_delta = прежний kKillRelationDelta), прогнанной через свидетелей:
// незамеченное убийство оставляет труп, но не дипломатию.
//
// Открытые вопросы владельцу из плана решены канонными дефолтами (сессия
// 2026-08-29, владелец спит): восприятие = чистые los/слух без броска
// «заметил» (первый вариант самого плана); игрок-свидетель = та же матрица
// (строка игрока — «игрок не особенный»). Вернуть бросок = правка одного
// предиката perceived().
