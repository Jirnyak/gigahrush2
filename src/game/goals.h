#pragma once

#include <cstdint>

#include "core/math.h"
#include "game/npc_pool.h" // Needs — спрос из нужд (один из источников, S13.1)
#include "game/room.h"     // FloorRooms — предмет выбора (S12)
#include "game/verb_table.h"

namespace giga::game {

// Издержка пути, очков за КЛЕТКУ. Число — из примера канона S13.3
// (данные владельца 2026-08-20): «своя жилая 47 − путь 8», «чужая ближе
// 17 − путь 2» — единица пути стоит одно очко предложения. Отсюда радиус
// кандидата ВЫВОДИТСЯ (S13.2): R = интерес / kGoalCostPerCell клеток —
// объявленные 30 очков глохнут за 30 клеток, полный интерес голодного к
// богатой столовой дотягивается через полмира.
inline constexpr float kGoalCostPerCell = 1.0f;

// Предложение точки под ногами — худший конец шкалы, малый но НЕНУЛЕВОЙ
// (S13.3: «пол под ногами 3 − путь 0 = 3»; число — из того же примера
// канона). Пол предлагает «спать» и «укрыться» — базовый минимум ФОРМЫ.
inline constexpr float kFloorPointOffer = 3.0f;

// Спрос «шататься» — малый, но никогда не ноль (S13.2: «замирающий NPC —
// дефект»). Данные, крутить смело; закон — только ненулевость.
inline constexpr float kWanderDemandFloor = 0.05f;

struct GoalPick {
    RoomId room = kNoRoom;   // kNoRoom = точка под ногами
    float score = 0.0f;      // очки победителя
    float distCells = 0.0f;  // честная тороидальная дистанция до цели
    VerbId topVerb = kVerbWander; // главный вклад — отладка/спич
};

// Спрос из НУЖД — один из источников контекста (S13.1). Расширяемость:
// новый фактор = ещё одна функция «контекст → добавь глаголу», выбор цели
// не трогается; если фактор требует правки goals_pick_room — это дефект.
void goals_demand_from_needs(const Needs& n, float demand[kVerbCount]);

// Выбор комнаты (плюс точка под ногами) одной суммой. Предложение комнаты =
// ОБЪЯВЛЕНО + ОСНАЩЕНИЕ/ЗАПАС (declared + supply, S12.4); СРЕДА/ФОРМА/
// НАРОД приезжают своими системами теми же слагаемыми. Ничью решает
// физика: интерес → расстояние (джиттер личности — инкремент E).
GoalPick goals_pick_room(const float demand[kVerbCount],
                         const FloorRooms& rooms, const vec3& fromPos);

} // namespace giga::game
