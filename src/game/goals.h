// goals.h — ЧЕСТНЫЙ ВЫБОР ЦЕЛИ (CANON S13; план agent-goals, инкремент A).
//
//   score(агент, цель) = Σ спрос[глагол] · предложение[глагол]
//                      − издержки (путь; толпа/опасность/территория — далее)
//                      + связь (дом/работа/репутация — инкремент E)
//
// ОДНА сумма, ноль особых случаев (S13.2): ветка по виду цели — дефект,
// фолбэк «ничего не нашлось» — дефект (S13.9). Этот заголовок — новый скорер
// РЯДОМ со старым score_intents: инкремент A вызывает его в отладку
// (GIGA_GOALS_DBG=1) и на движение НЕ влияет; переключение движения —
// инкремент C, смерть score_intents — F.
//
// Виды целей: ТОЧКА под ногами (кандидат ВСЕГДА — пустого списка нет по
// построению) + КОМНАТЫ этажа (радиус-отбор бинами) + КАНДИДАТЫ каллера
// (инкремент B): сущности — только воспринимаемые, отбор АКУСТИКОЙ И
// СОБЫТИЯМИ (решение владельца 2026-09-06: журнал шумов = «заметил» со
// старением, дистанция путевая по скелету; los_clear мёртв, sub_march на
// пер-тик пути запрещён — los.h); полевые цели — тем же кандидатом с
// нулевым путём.
#pragma once

#include <cstdint>

#include "core/math.h"
#include "game/npc_pool.h" // Needs — спрос из нужд (один из источников, S13.1)
#include "game/room.h"     // FloorRooms — предмет выбора (S12)
#include "game/verb_table.h"

namespace giga::game {

// Издержка пути, очков за КЛЕТКУ. Число — из примера канона S13.3
// (данные владельца 2026-08-20): «своя жилая 47 − путь 8», «чужая ближе
// 17 − путь 2» — единица пути стоит одно очко предложения. Отсюда радиус
// кандидата ВЫВОДИТСЯ (S13.2): R = интерес / kGoalCostPerCell клеток —
// объявленные 30 очков глохнут за 30 клеток, полный интерес голодного к
// богатой столовой дотягивается через полмира.
inline constexpr float kGoalCostPerCell = 1.0f;

// Предложение точки под ногами — худший конец шкалы, малый но НЕНУЛЕВОЙ
// (S13.3: «пол под ногами 3 − путь 0 = 3»; число — из того же примера
// канона). Пол предлагает «спать» и «укрыться» — базовый минимум ФОРМЫ.
inline constexpr float kFloorPointOffer = 3.0f;

// Спрос «шататься» — малый, но никогда не ноль (S13.2: «замирающий NPC —
// дефект»). Данные, крутить смело; закон — только ненулевость.
inline constexpr float kWanderDemandFloor = 0.05f;

// Полевая цель (S13.3, обобщение паники): предложение = значение поля
// [0,1] × эта шкала, путь НОЛЬ (всегда под ногами). 25 — середина
// авторской шкалы деклараций примера S13.3 (17..30): полное поле
// опасности спорит с объявленным укрытием через ~25 клеток пути, но
// проигрывает укрытию за стеной рядом («за стеной лучше, чем просто
// подальше»). Данные, крутить смело; закон — только «путь ноль» и
// «нет поля — нулевое предложение, цель не выигрывает никогда».
// Крутизна градиента — довесок инкремента C (там же шаг по градиенту).
inline constexpr float kFieldDangerOffer = 25.0f;

// Вид цели (S13.3) — строка ТАБЛИЦЫ «как дойти / что считать прибытием»,
// НЕ ветка скора: судятся все одной суммой, различие видов живёт у
// движения (инкремент C). if по kind в скоринге — дефект (S13.9).
enum class GoalKind : std::uint8_t { Point = 0, Room, Entity, Field };

// Кандидат, собранный ВОСПРИЯТИЕМ каллера (S13.3: сущности — только
// воспринимаемые; решение владельца 2026-09-06 — акустика + события).
// goals ничего не знает про ECS/шумы/поля: ему приносят готовый вектор
// предложения и ЧЕСТНУЮ дистанцию (путевую от акустики — стены уже в ней).
struct GoalCandidate {
    float offer[kVerbCount] = {}; // предложение кандидата (труп = его лут)
    float distCells = 0.0f;       // путь в клетках; поле = 0 (под ногами)
    std::uint32_t handle = 0;     // сущность/поле для каллера; скор не читает
    GoalKind kind = GoalKind::Entity;
};

struct GoalPick {
    GoalKind kind = GoalKind::Point;
    RoomId room = kNoRoom;   // при kind==Room; иначе kNoRoom
    std::uint32_t handle = 0; // при kind==Entity/Field — из кандидата
    float score = 0.0f;      // очки победителя
    float distCells = 0.0f;  // честная дистанция до цели (клетки)
    VerbId topVerb = kVerbWander; // главный вклад — отладка/спич
    std::uint32_t scored = 0; // целей просуждено — замер гейта B
};

// Скретч обхода бинов: штамп эпохи дедупит комнату, лежащую в нескольких
// бинах. Живёт у КАЛЛЕРА (не в FloorRooms): выбор цели — не мутация комнат,
// и два независимых решателя не должны делить состояние.
struct GoalsScratch {
    std::vector<std::uint16_t> stamp; // по комнате; == epoch → уже суждена
    std::uint16_t epoch = 0;
};

// Спрос из НУЖД — один из источников контекста (S13.1). Расширяемость:
// новый фактор = ещё одна функция «контекст → добавь глаголу», выбор цели
// не трогается; если фактор требует правки goals_pick — это дефект.
void goals_demand_from_needs(const Needs& n, float demand[kVerbCount]);

// ВЫБОР ЦЕЛИ одной суммой: точка под ногами (всегда) + комнаты этажа +
// кандидаты каллера (сущности из восприятия, полевые цели). Предложение
// комнаты = ОБЪЯВЛЕНО + ОСНАЩЕНИЕ/ЗАПАС (declared + supply, S12.4);
// СРЕДА/ФОРМА/НАРОД приезжают своими системами теми же слагаемыми.
// Ничью решает физика: интерес → расстояние (S13.2); двойная ничья
// (и по дистанции) — детерминизм порядка видов и меньший id, чтобы
// результат не зависел от порядка обхода (джиттер личности — инкремент E).
//
// Комнаты режутся ВЫВЕДЕННЫМ радиусом (S13.2, инкремент B): обход бинов
// шеллами от агента; бин не может дать больше, чем Σ спрос·потолок −
// нижняя грань пути, и как только даже ничья недосягаема — обход
// останавливается. Результат тождественен полному перебору (гейт-оракул
// в suite_goals). Кандидаты судятся ДО комнат: хороший воспринимаемый
// лидер сужает радиус даром.
GoalPick goals_pick(const float demand[kVerbCount], const FloorRooms& rooms,
                    const GoalCandidate* cands, std::size_t candCount,
                    const vec3& fromPos, GoalsScratch& scratch);

} // namespace giga::game
