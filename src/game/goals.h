//   score(агент, цель) = Σ спрос[глагол] · предложение[глагол]
//                      − издержки (путь; толпа/опасность/территория — далее)
//                      + связь (дом/работа/репутация — инкремент E)
//
// ОДНА сумма, ноль особых случаев (S13.2): ветка по виду цели — дефект,
// фолбэк «ничего не нашлось» — дефект (S13.9). Этот заголовок — новый скорер
// РЯДОМ со старым score_intents: инкремент A вызывает его в отладку
// (GIGA_GOALS_DBG=1) и на движение НЕ влияет; переключение движения —
// инкремент C, смерть score_intents — F.
//
// Виды целей здесь: КОМНАТЫ этажа + ТОЧКА под ногами. Точка — кандидат
// ВСЕГДА, поэтому список не бывает пустым по построению. Сущности
// (только воспринимаемые) и полевые цели — инкремент B; ВНИМАНИЕ разведки
// 2026-09-05: los_clear мёртв, кандидатам-сущностям нужен событийный отбор
