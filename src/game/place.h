// Спрос — ТЫСЯЧНЫЕ (0..1000 = 0..1). Предложение — ОЧКИ той шкалы, которой
// модули объявляют комнаты (`src/game/floors/khrushi/khrushi_gen.cpp` даёт
// спальне 30, кухне 12, сортиру 20). Произведение делится на 1000 ОДИН раз, на
// сумме, а не на каждом слагаемом, — и результат снова очки. Путь — клетки,
// очко за клетку.
//
// Поэтому пример S13.3 воспроизводится арифметикой: тело, которое хочет спать
// на полную тысячу, в своей жилой комнате (объявлено 30 + койка 17) на восьми
// клетках получает 47 − 8 = 39, а видимая койка в коридоре — 17 − 1 = 16.
// Гейт сьюта считает ровно эти числа: несходящаяся размерность — тот дефект,
// который у соседнего проекта дал перекос ЗНАКА ×50–100 и держал на себе весь
// торговый канал мира.
//
// ===========================================================================
// РЕШЕНИЯ ВЛАДЕЛЬЦА 2026-10-01, ПОД КОТОРЫЕ ЭТОТ ФАЙЛ НАПИСАН
// ===========================================================================
// 1. СПРОС — ФОРМУЛОЙ ИЗ `Needs`, не колонкой пула. Он производное состояния,
//    поэтому в сейв не едет и версионировать нечего; новый источник спроса
//    есть новая функция «контекст → добавь столько-то такому-то глаголу»
//    (`demand_add_health` — первая такая, и она образец), а выбор места при
//    этом НЕ ТРОГАЕТСЯ вовсе. Это буквальный тест расширяемости S13.1.
// 2. ИЗДЕРЖКА — ПОКА ТОЛЬКО ПУТЬ. Расширение будет правкой ОДНОЙ функции
//    `place_cost`, а не скорера: толпа, чужая территория и опасность входят
//    туда слагаемыми, когда у них появится писатель. Сегодня у НАРОДА его нет
//    вовсе, а `owner` у всех трёх модулей равен нулю — слагаемое без писателя
//    есть тот самый класс, которого перепись насчитала восемнадцать штук.
// 3. ОСНАЩЕНИЕ И ЗАПАС НЕ РАЗВОДЯТСЯ. S12.4 задаёт предложение как ОДИН
//    вектор — сумму шести слагаемых, а S12.3 прямо пишет: «голодный ищет
//    высокое есть и ПОЛУЧАЕТ ОБА, не зная, из чего оно сложилось». Различие
//    «расходуется?» живёт у ПИСАТЕЛЕЙ (`supply_add_prop` против
//    `supply_add_item`), и они уже раздельны. Поэтому здесь читается сумма
//    `declared + supply`, и строка 11 реестра расхождений поправлена как
//    ПЕРЕОЦЕНЁННАЯ переписью.
//
