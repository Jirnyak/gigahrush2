// НАВ ПО ЗОНАМ, ЯРУС 1 — граф зон и таблица «сколько зон до цели».
//
// ЗАКОН (замысел владельца, [markoaudit/plans/zone-nav.md]): персонаж НЕ ищет
// путь. Он читает число и шагает в меньшее. Стоимость шага — несколько чтений
// из заранее посчитанных массивов, константа, не зависящая ни от размера мира,
// ни от расстояния до цели, ни — главное — от числа персонажей.
//
// Поле на весь мир построить нельзя: полей нужно столько, сколько целей.
// Поэтому ярусов два, и этот файл — первый:
//
//   ЯРУС 1 (здесь): зоны — узлы, смежность зон — рёбра. По графу печётся
//     таблица «сколько зон пройти от A до B». Граф на три порядка меньше мира:
//     2 097 152 клетки превращаются в ~15 тысяч узлов.
//   ЯРУС 2 (инкремент C): поле по клеткам ОДНОЙ зоны на каждую её соседку,
//     обрезанное границей зоны. Источник залива — вся граница с соседкой.
//
// ДВЕРЕЙ НЕТ, И ЭТО РЕШЕНИЕ (владелец 2026-10-06): «обобщённые зоны; есть
// множество зон в торе, и каждая локально через всех соседок, и так позволит
// связность всего мира». Дверь в прототипе была КЛЕТКОЙ особого типа, то есть
// сущностью; здесь ею была бы политика в общем коде, что CANON S10 запрещает, и
// целый вид дверей в этом дереве уже снесён (S17). Граница зоны — не сущность,
// а СЛЕДСТВИЕ раскраски `roomAt`: клетки моей зоны, у которых сосед из той
// зоны. Её не объявляют, её считают.
//
// ЧТО ЗНАЧИТ «СМЕЖНЫ» — ПРОХОДИМОСТЬ, А НЕ КАСАНИЕ. Две зоны по разные стороны
// глухой кладки касаются, но ребро между ними было бы ложью: ярус 2 повёл бы
// агента на границу, которую не перейти. Поэтому ребро есть тогда и только
// тогда, когда НАЙДЁТСЯ пара касающихся клеток, чью общую грань тело
// ПРОЛЕЗАЕТ — тот же единственный закон проходимости, что у нава
// ([world/clearance.h] `face_clearance`, габарит в субвокселях).
#pragma once

#include <atomic>
#include <cstddef>
#include <cstdint>
#include <vector>

#include "game/room.h" // RoomId, kNoRoom, FloorRooms — зоны и их раскраска

namespace giga {
class MacroGrid;

namespace game {

// Недостижимость — 0xFFFF, а не флаг и не −1 в знаковом типе. На объёме Z²
// два байта против четырёх есть разница между 434 МиБ и 870 (замер зон:
// [markoaudit/plans/zone-nav.md]).
inline constexpr std::uint16_t kZoneUnreachable = 0xFFFFu;

// ГРАФ ЗОН в CSR: `offset` на зону, `nbr` подряд.
//
// Почему CSR, а не `nbr[zone][kMaxNeighbours]`: у прототипа стоял кап
// CONNECTIONS = 128, и это было бы ЧИСЛО БЕЗ ПРОИСХОЖДЕНИЯ — сколько соседок у
// зоны в 3D, не выводится ни из чего (зона трогает соседок по плану яруса плюс
// ярус сверху и снизу). CSR не требует капа вовсе: степень считается первым
// проходом, и переполниться нечему. Плюс плотность — AGENTS.md «dense over
// sparse»: один вектор вместо Z векторов с кучами.
//
// Зоны индексируются с НУЛЯ (`RoomId` − 1): `RoomId` нумерует с единицы, потому
// что ноль у него занят `kNoRoom`, и тащить эту дыру в плоский массив значило бы
// платить строкой на каждый доступ.
struct ZoneGraph {
    std::uint32_t zones = 0;            // Z
    std::vector<std::uint32_t> offset;  // Z + 1, offset[0] == 0
    std::vector<RoomId> nbr;            // offset[Z] элементов, RoomId как есть

    bool built() const { return zones != 0 && offset.size() == zones + 1u; }

    // Соседки зоны `z` (нулевой индекс) — непрерывный диапазон.
    const RoomId* begin(std::uint32_t z) const {
        return nbr.data() + offset[z];
    }
    const RoomId* end(std::uint32_t z) const { return nbr.data() + offset[z + 1]; }
    std::uint32_t degree(std::uint32_t z) const {
        return offset[z + 1] - offset[z];
    }
};

// ТАБЛИЦА «ЗОНА → ЗОНА»: сколько рёбер графа пройти от A до B.
//
// Полная, Z² на u16 — решение владельца 2026-10-06 («берём, как в статье»), и
// довод тот же: именно ПОЛНОТА таблицы покупает константу на шаг. Считать
// лениво или держать в кеше значит получить промах, а промах означает, что
// кто-то посреди кадра встал считать волну — ровно та непредсказуемость, ради
// избавления от которой всё и строится.
struct ZoneDist {
    std::uint32_t zones = 0;
    std::vector<std::uint16_t> d; // zones², построчно по источнику

    bool built() const {
        return zones != 0 &&
               d.size() == static_cast<std::size_t>(zones) * zones;
    }
    std::uint16_t at(std::uint32_t from, std::uint32_t to) const {
        return d[static_cast<std::size_t>(from) * zones + to];
    }
    // ОЗУ по капу — печатать вслух на бейке: «бейк без замера прячет свою
    // регрессию».
    std::size_t bytes() const { return d.size() * sizeof(std::uint16_t); }
};

// Бейк графа: один обход `roomAt` плюс гранный клиренс на каждую пару
// касающихся клеток разных зон. Габарит — в субвокселях (тело NPC 4, вывод у
// потребителя, [game/embody.h]).
//
// Бейк-таймовый (вход на этаж / допекание, S9), не тик. Детерминирован: обход
// по порядку клеток, пары сортируются, значит порядок соседок один при любом
// расписании.
void bake_zone_graph(const FloorRooms& fr, const MacroGrid& grid, int size,
                     ZoneGraph& out);

// Бейк таблицы: обход в ширину по графу из КАЖДОЙ зоны.
//
// Параллель ПО ИСТОЧНИКАМ: строка таблицы принадлежит своему источнику нацело,
// значит записи воркеров дизъюнктны — тот же контракт непересекающихся записей,
// которого требует [core/jobs.h] ради бит-идентичного результата при любом
// числе потоков. `threads` 0 = все ядра. `cancel` опрашивается раз в ИСТОЧНИК;
// отменённый бейк есть МУСОР по контракту, вызывающий обязан его выбросить.
void bake_zone_dist(const ZoneGraph& g, ZoneDist& out, int threads = 0,
                    const std::atomic<bool>* cancel = nullptr);

// Куда шагнуть по ЯРУСУ 1: соседка зоны `from`, которая ближе к `to`, чем сама
// `from`. Возвращает `kNoRoom`, если шагать некуда (уже в цели, или цель
// недостижима). Это первое из двух чтений шага агента; второе — поле яруса 2.
//
// O(степени), а не O(1), и это сознательно: степень зоны — единицы, а таблица
// `next[A][B]` стоила бы ВТОРЫЕ Z² (ещё 434 МиБ) ради экономии двадцати чтений
// из уже горячей строки.
RoomId zone_next(const ZoneGraph& g, const ZoneDist& dist, RoomId from,
                 RoomId to);

} // namespace game
} // namespace giga
