// отпускалось тем же тиком («дошёл — отпускаем», `place.cpp`), а все три двери
// утоления звались только с ввода игрока. Две из них к тому же искали носителя
// камеры ПО ПОСТРОЕНИЮ (`use_best_food`/`use_best_drink` → `find_player`
// @needs.cpp, снесены 2026-11-14), а третья (`relieve_needs`) камеру не искала — она чистая
// функция над `Needs&`, — но второго вызывающего, кроме клавиши P, у неё не
// было. То есть толпа могла ЗАХОТЕТЬ и могла ПРИЙТИ, но не могла СДЕЛАТЬ — и
// умирала по построению, что и было названо долгом в шапке [game/needs.h].
//
// ПЕРЕПИСЬ ЖИВОГО ПРОГОНА (`--action nuzhdy`, этаж 6, 379 тел) назвала три
// причины, и ни одна из них не была той, которую я собирался лечить:
//   * 375 тел из 379 стоят ВНЕ объявленных комнат (коридоры и улица), то есть
//     «прибытие в комнату» для толпы — редкость, а не норма;
//   * ни одно тело не шло никуда (`pick=0`): при терпении строки глагола
//     (S13.5) средний житель хочет слишком слабо, чтобы обогнать цену пути
//     (1 очко за клетку), — и это ПРАВИЛЬНО, терпение для этого и заведено;
//   * жажде предлагали НОЛЬ комнат из 5700, при 145 жаждущих телах. Вода —
//     первый бар, который падает (static_assert в [game/needs.h]), поэтому
//     никакое деяние не спасло бы толпу, пока кран не объявлен модулем.
// Отсюда форма этого файла: деяние вешается не на СОБЫТИЕ прибытия, а на
// СОСТОЯНИЕ «стою там, где предлагают то, чего хочу».
//
// ===========================================================================
// ЗАКОНЫ
// ===========================================================================
// 1. ДЕЯНИЕ — ТАМ, ГДЕ СТОИШЬ, И ТОЛЬКО ПО ОТВЕТУ СУММЫ. Решает одна сумма
//    S13.2 (`place_pick`): пока она отвечает «ничего не обгоняет место под
//    ногами», тело ОСТАЁТСЯ, и вот это «остаётся» и есть время деяния. Тело с
//    целью идёт и не служит — иначе у выбора было бы два решателя, ровно та
//    болезнь, которую вылечил S13bis.
// 2. ГРАНУЛЯРНОСТЬ — КОМНАТА (она же зона), а не вещь. Это не поблажка, а тот
//    же закон, которым живёт прибытие: «предложение и глаголы живут НА ЗОНЕ, а
//    тело внутри зоны их и получает» ([game/place.cpp]). Моста «глагол →
//    ближайшая вещь в досягаемости» в дереве нет вовсе, и он приедет вместе с
//    последней ногой пути (один проход ведения) — долг назван в S24.
// 3. РАСХОДУЕМОЕ РАСХОДУЕТСЯ (S12.5). Если в комнате ЛЕЖИТ предмет, утоляющий
//    этот глагол, деяние берёт ЕГО: предмет исчезает, запас комнаты падает,
//    следующий голодный видит меньшее «есть». Величину в этом случае называет
//    строка предмета (`apply_consumable`), а не комната, — иначе у вопроса
//    «сколько даёт хлеб» было бы два ответа. Нерасходуемая часть предложения
//    (объявленное + оснащение) есть ВОЗМОЖНОСТЬ места и не тратится.
// 4. ЗАНЯТОСТЬ — ЧУЖАЯ (S22). Своего таймера здесь нет и быть не может:
//    деяние живёт окном `Acting` на слоте `Body`, длина — из колонки `dur_ms`
//    строки `actions.csv`. ОКНО — ПОТОК (2026-11-14, решение владельца «не итог
//    в конце, а по кванту»): каждый тик окна отдаёт свою долю объёма,
//    курсор доставки — `applyTicks` (`acting_take_flow`), опрос, пропустивший
//    тики, получает их разом. До потока контакт стоял В КОНЦЕ окна.
// 5. ТЕЛО УШЛО ОТ ДЕЛА — ОКНО РВЁТСЯ (`kBreakLeave`, причина из маски строки).
//    Кто увёл тело, решает развилка решателя у ЕДИНСТВЕННОГО вызывающего
//    (`serve_step`): жителя — заявка сильнее дела (бегство, наряд — S25),
//    человека — его собственная команда движения. Сорванный поток отдал ровно
//    то, что успел; предмет, взятый в начале, назад не возвращается.
// 6. СКОРОСТЬ ПИШЕТ ОДИН. Этот файл НЕ рулевой: он отвечает «тело занято, не
//    веди его», а держит жителя на месте проход дела (`place_errand_step`)
//    заявкой `Hold`, которую исполняет единственный писатель `guide_step`
//    (S25). Человека не держит никто: его ведёт ввод, и уйти — его право
//    (закон 5).
//
// ===========================================================================
// ОДНА ДВЕРЬ УТОЛЕНИЯ ДЛЯ ЛЮБОГО ТЕЛА (CANON S27.1, 2026-11-14)
// ===========================================================================
// До 2026-11-14 дверей было ДВЕ: житель утолялся здесь, окном `Acting`, а
// носитель камеры — мгновенно, `use_best_food/drink@needs.cpp` (своим поиском
// тела по `CameraTag` и вторым списанием HP за рискованную еду в приложении),
// клавиша P — `relieve_needs` прямо из приложения. Решение владельца: «игрок ест,
// пьёт и спит обоими способами — кнопкой „Использовать“ и деянием на месте — и оба
// входа ведут в ОДНУ дверь, источник которой — своя сумка или запас комнаты».
//
// ФОРМА: дверь одна — `serve_start(тело, глагол, предмет)`; она же выбирает
// источник и берёт предмет В НАЧАЛЕ окна (окно его помнит — `ActWindow::item`,
// 0 = утоление местом или телом); эффект течёт квантами (`flow_effect`),
// опрашивает окна один проход (`serve_step`) — для любого тела,
// какого бы рода ни был его решатель. Различаются только ВЫБИРАТЕЛИ — кто решает
// «что сделать», и это развилка решателя S13.7a, а не вторая дверь:
//   * житель — одна сумма S13 (`serve_begin` → `serve_pick`);
//   * человек — сам: кнопкой «Использовать» (`serve_item_verb` — глагол
//     выбранного предмета), клавишей F на месте (`serve_place_verb` — что место
//     даёт ему сейчас; табличка показывает это ДО нажатия) и клавишей P
//     (облегчение — исключение владельца из закона чистки клавиш 2026-08-28).
//
// ИСТОЧНИКИ ВЕЛИЧИНЫ (выбирает `serve_start` в начале окна), по порядку:
//   1. ПРЕДМЕТ СВОЕЙ СУМКИ (`item != 0`) — ровно тот, что выбран; комната не
//      нужна. Берётся из сумки сразу; цена рискованной еды — ОДИН раз, сразу,
//      каналом, которого не видит броня.
//   2. РАСХОДУЕМОЕ КОМНАТЫ — лежащее в ящике; берётся сразу, запас падает.
//   3. ТЕЛО — у облегчения: объём называет тело (`needs_body_total`:
//      опорожняешься целиком за окно), комната не нужна; место решает только
//      лужу, уместность судит свидетель (S19).
//   4. МЕСТО — возможность комнаты (объявлено + оснащение − лежащее на полу).
//
