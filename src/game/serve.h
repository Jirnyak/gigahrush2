// До 2026-11-08 цикл нужд был РАЗОМКНУТ в одном месте: прибывшее тело
// отпускалось тем же тиком («дошёл — отпускаем», `place.cpp`), а все три двери
// утоления звались только с ввода игрока. Две из них к тому же искали носителя
// камеры ПО ПОСТРОЕНИЮ (`use_best_food`/`use_best_drink` → `find_player`
// @needs.cpp), а третья (`relieve_needs`) камеру не искала — она чистая
// функция над `Needs&`, — но второго вызывающего, кроме клавиши P, у неё не
// было. То есть толпа могла ЗАХОТЕТЬ и могла ПРИЙТИ, но не могла СДЕЛАТЬ — и
// умирала по построению, что и было названо долгом в шапке [game/needs.h].
//
// ПЕРЕПИСЬ ЖИВОГО ПРОГОНА (`--action nuzhdy`, этаж 6, 379 тел) назвала три
// причины, и ни одна из них не была той, которую я собирался лечить:
//   * 375 тел из 379 стоят ВНЕ объявленных комнат (коридоры и улица), то есть
//     «прибытие в комнату» для толпы — редкость, а не норма;
//   * ни одно тело не шло никуда (`pick=0`): при терпении строки глагола
//     (S13.5) средний житель хочет слишком слабо, чтобы обогнать цену пути
//     (1 очко за клетку), — и это ПРАВИЛЬНО, терпение для этого и заведено;
//   * жажде предлагали НОЛЬ комнат из 5700, при 145 жаждущих телах. Вода —
//     первый бар, который падает (static_assert в [game/needs.h]), поэтому
//     никакое деяние не спасло бы толпу, пока кран не объявлен модулем.
// Отсюда форма этого файла: деяние вешается не на СОБЫТИЕ прибытия, а на
// СОСТОЯНИЕ «стою там, где предлагают то, чего хочу».
//
// ===========================================================================
// ЗАКОНЫ
// ===========================================================================
// 1. ДЕЯНИЕ — ТАМ, ГДЕ СТОИШЬ, И ТОЛЬКО ПО ОТВЕТУ СУММЫ. Решает одна сумма
//    S13.2 (`place_pick`): пока она отвечает «ничего не обгоняет место под
//    ногами», тело ОСТАЁТСЯ, и вот это «остаётся» и есть время деяния. Тело с
//    целью идёт и не служит — иначе у выбора было бы два решателя, ровно та
//    болезнь, которую вылечил S13bis.
// 2. ГРАНУЛЯРНОСТЬ — КОМНАТА (она же зона), а не вещь. Это не поблажка, а тот
//    же закон, которым живёт прибытие: «предложение и глаголы живут НА ЗОНЕ, а
//    тело внутри зоны их и получает» ([game/place.cpp]). Моста «глагол →
//    ближайшая вещь в досягаемости» в дереве нет вовсе, и он приедет вместе с
//    последней ногой пути (один проход ведения) — долг назван в S24.
// 3. РАСХОДУЕМОЕ РАСХОДУЕТСЯ (S12.5). Если в комнате ЛЕЖИТ предмет, утоляющий
//    этот глагол, деяние берёт ЕГО: предмет исчезает, запас комнаты падает,
//    следующий голодный видит меньшее «есть». Величину в этом случае называет
//    строка предмета (`apply_consumable`), а не комната, — иначе у вопроса
//    «сколько даёт хлеб» было бы два ответа. Нерасходуемая часть предложения
//    (объявленное + оснащение) есть ВОЗМОЖНОСТЬ места и не тратится.
// 4. ЗАНЯТОСТЬ — ЧУЖАЯ (S22). Своего таймера здесь нет и быть не может:
//    деяние живёт окном `Acting` на слоте `Body`, длина — из колонки `dur_ms`
//    строки `actions.csv`, контактный кадр — КОНЕЦ окна (съел — наелся).
//    Эффект падает ровно один раз (бит `applied`), поэтому опрос, пропустивший
//    свой тик, эффекта не теряет.
// 5. УГРОЗА СТАРШЕ ДЕЛА. Тело, которое забрало бегство, рвёт своё окно
//    (`kBreakThreat` — причина из маски строки). Обрыв ДО контакта = эффекта
//    не было; у деяний нужды контакт в конце, значит прерванное деяние не
//    кормит, и это правильно.
// 6. СКОРОСТЬ ПИШЕТ ОДИН. Этот файл НЕ рулевой: он отвечает «тело занято, не
//    веди его», а держит тело на месте сам проход ведения
//    (`place_errand_step`) — тем же токеном `MotionOwner`, которым он ведёт.
//    Третьего писателя `Velocity` заход не заводит (очередь: один проход
//    ведения).
//
