// Что сделал один проход по телам. Счётчики — не телеметрия ради телеметрии:
// «толпа умирает» есть утверждение о ПРИЧИНЕ, а причин у недобора три, и в
// счётчиках прохода ведения они неразличимы (см. шапку).
struct ServeTick {
    std::uint32_t holding = 0;  // тел держит открытое окно деяния
    std::uint32_t began = 0;    // деяний начато этим тиком
    std::uint32_t applied = 0;  // окон отдало ВСЁ (последний квант потока)
    std::uint32_t broke = 0;    // деяний сорвано: тело ушло от дела (закон 5)
    std::uint32_t corridor = 0; // тел стоит вне комнат: деяние недоступно ПО МЕСТУ
    std::uint32_t nothing = 0;  // тел в комнате, которой нечего им дать
    std::uint32_t consumed = 0; // начато над ПРЕДМЕТОМ ИЗ ЯЩИКА (взят, запас упал)
    std::uint32_t bag = 0;      // начато над ПРЕДМЕТОМ СВОЕЙ СУМКИ (взят)
    std::uint32_t puddles = 0;  // облегчений вне места, которое даёт сортир (лужа)
    std::uint32_t byVerb[kVerbCount] = {}; // чем именно начинали
    // Σ очков, которые деяния СДВИНУЛИ: у запаса они легли на бар, у сортира —
    // снялись с давления (бар там падает, S24.6), поэтому «легло на бары» было
    // бы ложью на четверти строк. ДРОБЬ, а не целое: окно-поток отдаёт за тик
    // сотые доли очка, и целое округлило бы весь поток в ноль.
    float reliefSum = 0.0f;
};

// ЧТО ЭТО МЕСТО МОЖЕТ ДАТЬ ЭТОМУ ТЕЛУ. Побочный выход — та же пара
// «глагол × предложение», которой считает `place_interest`, но суженная до
// глаголов, У КОТОРЫХ ЕСТЬ СТРОКА ДЕЯНИЯ (`kVerbAction`): нельзя начать
// деяние, которого нет в данных, а нельзя — значит и выбирать его незачем.
//
// `verb == kVerbCount` — «нечего дать»: либо спрос ноль, либо предложение
// ноль, либо у глагола нет строки. Все три неразличимы НАМЕРЕННО: вызывающему
// нужно одно — начинать деяние или нет.
struct ServePick {
    VerbId verb = static_cast<VerbId>(kVerbCount);
    std::int32_t offer = 0;   // declared + supply по этому глаголу, очки
    std::int64_t term = 0;    // спрос × предложение — слагаемое ТОЙ ЖЕ суммы
};
ServePick serve_pick(const Room& r, const DemandE3 demand[kVerbCount]);

// Контекст шва: те же четыре вещи, что у любого прохода игрового слоя.
struct ServeCtx {
    Registry& reg;
    NpcPool& pool;
    FloorRooms& fr;        // не const: расходуемая часть предложения падает
    EventBus* bus = nullptr; // nullptr законен: деяние свершится, факт не поедет
    std::uint64_t tick = 0;
    // Мир слоя — только для ЛУЖИ облегчения вне места, которое даёт сортир
    // (тот же универсальный стейн, что кровь, [world/stain.h]). nullptr
    // законен: опорожнение и деяние S19 свершатся, лужи не будет (стенды без
    // мира). Грязные клетки должны зеркалу вокселей — их забирает вызывающий.
    World* world = nullptr;
    std::vector<std::uint32_t>* stainDirty = nullptr;
};

// ПОЧЕМУ ДВЕРЬ ОТКАЗАЛА — значением, а не тишиной: человеку нужна строка
// («не хочется» и «здесь нечем» — разные ответы), прибору — счётчик.
enum class ServeRefusal : std::uint8_t {
    None = 0, // окно открыто
    Busy,     // слот тела занят: окно идёт или ещё должно свой эффект
    NoRow,    // у глагола нет строки деяния (`kVerbAction`) — это данные
    NoItem,   // предмета нет в своей сумке
    Full,     // этому бару некуда расти; у облегчения — нечем облегчаться
    NoPlace,  // место этот глагол не даёт (коридор, пустая комната)
};

// Слово отказа для стекла — по образцу `craft_fail_text@craft.h`: причина
// значением, слова рядом с ней. ⚠ Литерал UI в C++ — долг двери строк (CANON
// S27.4, следующий пункт очереди): переедет в таблицу строк вместе с худом.
const char* serve_refusal_text(ServeRefusal r);

// ОДНА ДВЕРЬ ОТКРЫТИЯ ОКНА УТОЛЕНИЯ — для любого тела. Окно `Body`, строка
// `kVerbAction[verb]`, длина `dur_ms`, окно-поток (эффект квантами всё окно).
// `item != 0` — предмет СВОЕЙ сумки (`pool.inventory(id)`), окно его запомнит;
// `item == 0` — утоление местом (или телом — у облегчения).
//
// Отказ судится ТЕМ ЖЕ законом, которым сядет эффект, а не вторым switch'ем
// «глагол → бар»: пробный прогон `needs_satisfy` / `apply_consumable` на КОПИИ
// строки нужд (решения ревью 2026-11-14). Ноль легшего = отказ.
//
// ДЛИНА ОКНА — У ГЛАГОЛА, а не у источника: хлеб из сумки — та же 20-секундная
// трапеза, что у плиты, таблетка снотворного (глагол sleep) — тот же 90-секундный
// сон. Две строки на глагол генератор запрещает (S24.4); нюанс назван владельцу.
ServeRefusal serve_start(const ServeCtx& ctx, Entity e, NpcId id,
                         const vec3& pos, VerbId verb, ItemId item,
                         ServeTick& out);

// ГЛАГОЛ ПРЕДМЕТА — аргмакс `kItemVerbs` среди глаголов, у которых есть строка
// деяния; `kVerbCount` = «этим не утолить» (аптечка: у `heal` строки нет —
// данные). Ничья — младшему глаголу. Его же спрашивает инвентарь, рисуя кнопку
// «Использовать»: кнопки без двери не бывает.
VerbId serve_item_verb(ItemId item);

// ЧТО МЕСТО ДАСТ ЭТОМУ ТЕЛУ СЕЙЧАС — выбиратель ЧЕЛОВЕКА (S13.7a: за носителя
// камеры решает человек, сумма жителя с её коленом терпения ему не указ — иначе
// F в кухне при еде 50 отвечал бы «не хочется»). Только глаголы, которые место
// ПРЕДЛАГАЕТ (объявлено + запас > 0): F в коридоре не делает ничего, облегчение
// где застало — клавиша P, а не F (жалоба владельца 2026-08-28 «жму E у двери, а
// персонаж мочится»). Среди предложенных — тот, чьему бару больше всего некуда
// деться (наибольшая недостача, пробой `needs_satisfy` на копии); ничья —
// младшему глаголу. `kVerbCount` = место ничего не даст. Табличку фокуса и
// действие F строит ОДИН этот вызов: «F исполняет ровно то, что показано».
//
// Величина места — ТА ЖЕ, что потечёт квантами: объявлено + запас − лежащее на
// полу (пикапы деянием не берутся); `layer` нужен ровно для этого вычета.
VerbId serve_place_verb(const ServeCtx& ctx, NpcId id, const vec3& pos,
                        LayerId layer);

// ОПРОС И НАЧАЛО — ДВА РАЗНЫХ ВОПРОСА, А НЕ ОДИН РАЗРЕЗАННЫЙ.
//
// Порядок обязателен и доказан мутацией: «занят?» спрашивают ДО суммы, иначе
// тело, уже легшее спать, на следующем же кадансе пере-выбора получило бы
// новую цель и ушло бы досыпать на ходу, а окно закрылось бы само и уронило
// эффект по дороге. Занятость монотонна (S22.1) — значит и спрашивается
// первой.
//
// `pos`/`layer` передаются, а не читаются из `Transform` сущности: вызывающий
// их уже держит (он их и обходит), а второе чтение того же места — лишний
// шанс разойтись.

// ЗАНЯТ ЛИ ДЕЯНИЕМ — и отдать созревшие кванты потока. true = окно идёт, тело
// вести нельзя (вызывающий держит его на месте, закон 6).
//
// Кванты снимаются ДО вопроса «занят ли»: последний квант созревает на тике,
// когда `act_busy` уже ложь. Курсор ([game/action.h] `acting_take_flow`) делает
// опрос идемпотентным: тело, пропустившее тики, получает их разом.
bool serve_busy(const ServeCtx& ctx, Entity e, NpcId id, const vec3& pos,
                LayerId layer, ServeTick& out);

// ВЫБИРАТЕЛЬ ЖИТЕЛЯ: начать деяние на месте, если место даёт то, чего тело
// хочет по одной сумме (`serve_pick`). true = началось, тело держат. Зовётся из
// `place_errand_step` РОВНО в точке, где сумма ответила «ничего не обгоняет
// место под ногами». Окно открывает та же дверь `serve_start`.
bool serve_begin(const ServeCtx& ctx, Entity e, NpcId id, const vec3& pos,
                 ServeTick& out);

// ЧИСТЫЙ ВОПРОС «ДЕРЖИТ ЛИ ТЕЛО ДЕЯНИЕ» — без побочных эффектов. Открыто окно
// деяния нужды: идёт по времени ИЛИ ещё должно свой конечный эффект
// (`act_open`). Второе — не перестраховка: если опрос этого тика тело не
// посетил, окно с неотданным хвостом потока иначе перезаписалось бы следующим
// выбором, и эффект пропал бы молча (Б1 ревью 2026-11-14).
bool serve_holding(const Registry& reg, Entity e, std::uint64_t tick);

// ОДИН ПОЛЛЕР ВСЕХ ОКОН ДЕЯНИЯ НА СЛОЕ — у любого тела, какого бы рода ни был
// его решатель. Порядок внутри тела: (1) тело ушло от дела → обрыв `leave`
// (закон 5); (2) созревшие кванты → эффект (`serve_busy`); (3) открыто →
// `holding`. Обрыв СТАРШЕ кванта: тело, которое на этом тике увели,
// не кормится (гейт `suite_place`).
//
// МЕСТО В ТИКЕ — ПОСЛЕ всех заявителей сильнее дела (`ai_step` — бегство,
// `ai_patrol_step` — наряд) и ПЕРЕД `place_errand_step`, который спрашивает
// только `serve_holding`. До 2026-11-14 опрос жил внутри прохода дела, и
// поэтому окна носителя камеры не опрашивал НИКТО (проход дела обслуживает
// только жителей): дверь утоления не могла стать одной, пока опрос был
// привязан к решателю.
