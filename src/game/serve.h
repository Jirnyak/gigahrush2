// прибор и задуман.
//
// Своего СОСТОЯНИЯ у деяния нет вовсе, и это главное свойство файла: «чем
// тело занято» держит `Acting` (S22), «зачем» — `ErrandPlan::verb`, «сколько
// дало место» — вектор комнаты. Новой строки мира заход не заводит.
