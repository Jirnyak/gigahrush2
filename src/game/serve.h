namespace giga::game {

class EventBus;

// Что сделал один проход по телам. Счётчики — не телеметрия ради телеметрии:
// «толпа умирает» есть утверждение о ПРИЧИНЕ, а причин у недобора три, и в
// счётчиках прохода ведения они неразличимы (см. шапку).
struct ServeTick {
    std::uint32_t holding = 0;  // тел держит открытое окно деяния
    std::uint32_t began = 0;    // деяний начато этим тиком
    std::uint32_t applied = 0;  // контактных кадров снято — эффект упал
    std::uint32_t broke = 0;    // деяний сорвано угрозой
    std::uint32_t corridor = 0; // тел стоит вне комнат: деяние недоступно ПО МЕСТУ
    std::uint32_t nothing = 0;  // тел в комнате, которой нечего им дать
    std::uint32_t consumed = 0; // из них утолено ПРЕДМЕТОМ (запас упал)
    std::uint32_t byVerb[kVerbCount] = {}; // чем именно начинали
    // Σ очков, которые деяния СДВИНУЛИ: у запаса они легли на бар, у сортира —
    // снялись с давления (бар там падает, S24.6), поэтому «легло на бары» было
    // бы ложью на четверти строк. Целое: дробь деяния меньше очка прибор
    // округляет вниз, и это сознательно — он мерит ЦИКЛ, а не бухгалтерию.
    std::int32_t reliefSum = 0;
};

// ЧТО ЭТО МЕСТО МОЖЕТ ДАТЬ ЭТОМУ ТЕЛУ. Побочный выход — та же пара
// «глагол × предложение», которой считает `place_interest`, но суженная до
// глаголов, У КОТОРЫХ ЕСТЬ СТРОКА ДЕЯНИЯ (`kVerbAction`): нельзя начать
// деяние, которого нет в данных, а нельзя — значит и выбирать его незачем.
//
// `verb == kVerbCount` — «нечего дать»: либо спрос ноль, либо предложение
// ноль, либо у глагола нет строки. Все три неразличимы НАМЕРЕННО: вызывающему
// нужно одно — начинать деяние или нет.
struct ServePick {
    VerbId verb = static_cast<VerbId>(kVerbCount);
    std::int32_t offer = 0;   // declared + supply по этому глаголу, очки
    std::int64_t term = 0;    // спрос × предложение — слагаемое ТОЙ ЖЕ суммы
};
ServePick serve_pick(const Room& r, const DemandE3 demand[kVerbCount]);

// Контекст шва: те же четыре вещи, что у любого прохода игрового слоя.
struct ServeCtx {
    Registry& reg;
    NpcPool& pool;
    FloorRooms& fr;        // не const: расходуемая часть предложения падает
    EventBus* bus = nullptr; // nullptr законен: деяние свершится, факт не поедет
    std::uint64_t tick = 0;
};

// ДВЕ ДВЕРИ, И ЭТО ДВА РАЗНЫХ ВОПРОСА, А НЕ ОДИН РАЗРЕЗАННЫЙ.
//
// Порядок обязателен и доказан мутацией: «занят?» спрашивают ДО суммы, иначе
// тело, уже легшее спать, на следующем же кадансе пере-выбора получило бы
// новую цель и ушло бы досыпать на ходу, а окно закрылось бы само и уронило
// эффект по дороге. Занятость монотонна (S22.1) — значит и спрашивается
// первой.
//
// `pos`/`layer` передаются, а не читаются из `Transform` сущности: вызывающий
// их уже держит (он их и обходит), а второе чтение того же места — лишний
// шанс разойтись.

// ЗАНЯТ ЛИ ДЕЯНИЕМ — и снять контактный кадр, если он наступил. true = окно
// открыто, тело вести нельзя (вызывающий держит его на месте, закон 6).
//
// Опрос контактного кадра стоит ЗДЕСЬ, а не в «начать»: у деяния нужды контакт
// — КОНЕЦ окна, то есть тик, на котором `act_busy` уже ложь. Бит
// одноразовости ([game/action.h]) делает опрос идемпотентным, поэтому тело,
// пропустившее свой тик (ушло со слоя, кадр без сим-подшага), эффекта не
// теряет.
bool serve_busy(const ServeCtx& ctx, Entity e, NpcId id, const vec3& pos,
                LayerId layer, ServeTick& out);

// НАЧАТЬ ДЕЯНИЕ НА МЕСТЕ, если место даёт то, чего тело хочет. true =
// началось, тело держат. Зовётся из `place_errand_step` РОВНО в точке, где
// сумма ответила «ничего не обгоняет место под ногами».
bool serve_begin(const ServeCtx& ctx, Entity e, NpcId id, const vec3& pos,
                 ServeTick& out);

// УГРОЗА СТАРШЕ ДЕЛА: тело забрал другой владелец движения — рвём открытое
// окно деяния нужды. Боевые окна не трогает: причина `kBreakThreat` в их
// маске не стоит, и `break_action` сам откажет.
void serve_break_threat(Registry& reg, Entity e, std::uint64_t tick,
                        ServeTick& out);

} // namespace giga::game

