// ОДИН ПРОХОД ВОСПРИЯТИЯ — зрение и слух ОДНОЙ системой, агностично.
//
// ЗАКОН ВЛАДЕЛЬЦА (CANON S25.8, дословно): «есть зрение и слух… можно дефолт
// сделать зрение, а второй приоритет слух, но например если будут мобы без
// зрения, то они будут на слух только — надо только сделать системно,
// универсально, агностично. Использовать естественно мир клеточный связный и
// запечённые поля: видят они буквально КОНУС ложат на клеточки, а слух через
// поле звука запечённое, то есть диффузно».
//
// ЧТО БЫЛО ДО ЭТОГО ФАЙЛА (перепись 2026-11-09, не предположение). Зрения как
// системы не было: тело «замечало» тело СФЕРОЙ без геометрии — СЕМЬ
// независимых сканов «ближайшее тело в шаре» с тремя разными радиусами
// (`behaviour_aggro_radius` 2.15…30 м в `wander.cpp` и `investigate.cpp`,
// `kHuntRadius` 6 м в `hunt.cpp`, `kFeudRadius` 8 м в `faction_relations.cpp`),
// ни один из которых не спрашивал ни угла, ни заслонения. ЗАМЕР прибором
// (`--action zrenie`, до лечения): на этаже 6 СКВОЗЬ СТЕНУ идёт **25.7 %**
// контактов монстров, на падике — **52 %** контактов вражды; слух сквозь
// материю — **69-90 %** всего услышанного. Четыре копии цикла «найти носителя
// камеры» (`wander.cpp`, `combat.cpp`, `investigate.cpp`, `rumour.cpp`) и были
// тем «игрок чем-то особен», которое снёс владелец.
//
// ТРИ ОТСЕЧКИ ПЕРЕД ОДНОЙ ДОРОГОЙ. Порядок — дешёвое первым, и он не вкус:
// §66 уже заплатил 631 мкс/деяние за луч без отсечек и вылечился ×162 тем, что
// поставил перед лучом слух и строку матрицы (`witness.cpp:146-170`).
//   1. слой и дистанция² (тороидальная, `wrap_dist2`) — радиус из строки;
//   2. КОНУС по скалярному произведению со взглядом тела ([game/look.h]) —
//      угол из строки, и он агностичен к тому, ЧТО в клетке;
//   3. ЗАСЛОНЕНИЕ — одна дверь `sight_blocked`, см. ниже.
//
// СЛЕПОТА — СТРОКА ТАБЛИЦЫ, А НЕ ВЕТКА В КОДЕ: `fovCos > 1` в строке означает
// «конус пуст» ⇒ тело не видит никогда и ведётся слухом ПО ПОСТРОЕНИЮ. Кода
// под слепоту здесь нет вовсе.
//
// ЗРЕНИЕ СТАРШЕ СЛУХА — РАНГОМ, А НЕ ПОРЯДКОМ ВЫЗОВОВ (решение владельца).
// Сегодня было ровно наоборот и держалось тем, что `investigate_step` стоит в
// кадре ПОСЛЕ прогулки: моб, вцепившийся в жителя, бросал его на любой
// выстрел. Теперь зрение заявляет `SteerRank::Chase`, слух — `SteerRank::Noise`,
// и `Noise < Chase` в перечислении ([game/guide.h]) — арбитраж стал
// наблюдаемым, а CANON S25.2 прямо называет «порядок вызовов» непроверяемой
// формой арбитража.
