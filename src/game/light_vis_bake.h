// Светосетка ВЫВОДИТСЯ из макросетки, не назначается: клетка света = 2×2×2
// макроклетки (маппинг дренажа карва — сдвиг на бит), значит измерение —
// kMacroDim/2 и клетка — 2·kCellSize. Рендер обязан совпадать
// (gpu::kGridDimX == kLightVisDim — static_assert на шве в app).
inline constexpr int kLightVisDim = kMacroDim / 2; // 64
inline constexpr std::size_t kLightVisCells =
    static_cast<std::size_t>(kLightVisDim) * kLightVisDim * kLightVisDim;
inline constexpr float kLightVisCellM = kCellSize * 2.0f; // 4 м

inline std::size_t light_vis_index(int x, int y, int z) {
    x &= (kLightVisDim - 1);
    y &= (kLightVisDim - 1);
    z &= (kLightVisDim - 1);
    return static_cast<std::size_t>(x) +
           static_cast<std::size_t>(y) * kLightVisDim +
           static_cast<std::size_t>(z) * kLightVisDim * kLightVisDim;
}

// Всё, что флуду нужно знать о лампе. Индекс в массиве = стабильный id слота
// статик-таблицы света (та же нумерация, что uPointLights[0..staticCount)).
struct LightVisLamp {
    vec3 pos{0.0f, 0.0f, 0.0f};
    float radiusM = 0.0f;
    // Цвет лампы. (Единственным потребителем был синтез кластеров, удалённый
    // 2026-08-23; поле оставлено — оно описывает лампу, а не механизм.)
    vec3 color{1.0f, 1.0f, 1.0f};
};

// КЛАСТЕРЫ УДАЛЕНЫ 2026-08-23 (решение владельца). Механизм не работал ни
// одного кадра: биннинг (light_grid.comp) выбрасывал каждую кластерную
// ссылку по гварде `id >= staticCount` (98304 против ~12646), а ветка
// потребителя была мёртвым кодом. Цена бага — обрезка списка клетки до 8
// честных ламп при среднем 10.6: состав решался поклеточно, и на границах
// 4-метровых клеток свет и тени рвались прямоугольниками. Клетка снова
// держит весь свой список (до slots = 63).

// БИТ ДИЛАТАЦИИ в id списка клетки (находка аудита 2026-08-23 №1: ранг лампы
// считался чистой геометрией, и перекрытые лампы дилатации тратили теневые
// лучи пикселя наравне с видимыми). Лампа, попавшая в список НЕ прямым лучом,
// а расширением на соседа (страховка сэмплирования), несёт старший бит id;
// биннинг (light_grid.comp) штрафует её скор на +1.0 — геометрический скор
// внутрирадиусной лампы ≤ 1 по построению, поэтому ВСЕ видимые ранжируются
// выше ВСЕХ перекрытых, и теневой бюджет пикселя уходит видимым. Сама лампа
// из списка не выпадает — ошибка по-прежнему излишком, не потерей.
// CPU-читатели списков обязаны маскировать id; в шейдер бит едет дефайном
// GIGA_LAMP_DILATED_BIT (CMake парсит ЭТУ строку — не переименовывать).
inline constexpr std::uint32_t kLampDilatedBit = 0x80000000u;
inline constexpr std::uint32_t kLampIdMask = kLampDilatedBit - 1u;

// Выход бейка: на клетку светосетки — (1 + slots) слов u32 в лейауте
// GpuGridCell (count, id[slots]), отсортированных по вкладу (лучший первым),
// готовых к memcpy в стейджинг GPU. slots приходит от рендера параметром —
// game лейаут-агностичен, корневая константа kGridCellBytes живёт в
// gpu_light_grid.h.
struct LightVisBake {
    std::vector<std::uint32_t> cells;
    std::uint32_t slots = 0;
    std::uint32_t lampCount = 0;
    float rMaxM = 0.0f; // максимальный радиус статика — вход дренажа карва
    std::uint32_t litCells = 0;
    std::uint32_t overflowCells = 0; // клеток с достижимыми > slots (вслух!)
    std::uint32_t maxPerCell = 0;
    // Среднее ламп на ОСВЕЩЁННУЮ клетку — главный перф-датчик: кадр GPU
    // пропорционален толщине списков (замер 2026-08-20: таблица 12552 ->
    // 21 мс, таблица 8 -> 5 мс), и ужать его может только строгость бейка.
    float meanPerCell = 0.0f;
    // Средняя длина УПАКОВАННОГО списка (после top-K+кластеры) — то, что
    // реально платит пиксель; сравнивать с meanPerCell (достижимых).
    float packedMeanPerCell = 0.0f;
    float bakeMs = 0.0f;

    bool valid() const { return !cells.empty(); }
    std::size_t resident_bytes() const {
        return cells.capacity() * sizeof(std::uint32_t);
    }
};

// Свет доходит от `from` до точки за stopShortM метров до `to`? Двухуровневая
// правда: единственный субвоксельный марш дерева ([world/los] sub_march) с
// поправками света из шапки (эмиссив прощён, клетка `from` проходима
// принудительно). Публична, потому что это И закон бейка, И предмет прямых
// тестов сьюта (стена блокирует, щель пропускает, неон светит из тела).
bool light_ray_passes(const MacroGrid& grid, const vec3& from, const vec3& to,
                      float stopShortM = 0.0f);

// CPU-скор клетки — та же математика, что light_grid.comp
// dist_sq_point_aabb_toroidal: d² от точки до AABB клетки светосетки по тору,
// делённый на r². 0 = лампа внутри клетки, 1 = едва касается, >1 = вне.
float light_cell_score(const vec3& lampPos, float radiusM, int cx, int cy,
                       int cz);

// Бейк: 9-лучевая субвоксельная видимость + дилатация от каждой лампы,
// транспонирование в списки клеток, top-slots по вкладу с подсчётом
// переливов. Детерминирован и НЕ зависит от числа потоков: лампы делятся на
// непрерывные чанки ([core/jobs.h]), выход склеивается в порядке ламп.
// cancel — узловая отмена (гранулярность — лампа). `grid` — живой на Fresh
// (синхронный бейк главного потока) или снапшот-копия воркера на Rebake.
// Паковка одна: top-slots по вкладу (кластерная ветка удалена 2026-08-23).
void bake_light_visibility(const MacroGrid& grid, const LightVisLamp* lamps,
                           std::size_t lampCount, std::uint32_t slots,
                           LightVisBake& out, int threads = 0,
                           const std::atomic<bool>* cancel = nullptr);

// FNV-1a содержимого клеток — пин воспроизводимости (GIGA_LIGHT_VIS_PIN,
// образец GIGA_VERLET_PIN).
std::uint64_t light_vis_fnv(const LightVisBake& b);

// --- Частичное допекание: дельта-лампы (carve-hitch.md, инкремент 3) --------
//
// Два факта, на которых стоит частичность:
//   1. rays_one_lamp — чистая функция (grid, lamp): одну лампу можно перепечь
//      изолированно, бит-в-бит с тем, что сделал бы полный бейк.
//   2. Карв только УБИРАЕТ материю ⇒ видимость только РАСШИРЯЕТСЯ ⇒ старые
//      списки после карва не врут, они могут только недоговаривать. Частичное
//      допекание — это ДОБАВКИ, а не перестройка.
// Затронутые лампы: луч лампа→клетка через дыру ⇒ дыра ближе R лампы (та же
// геометрия, что у шара дренажа выше). На плотности ламп падика это ~44 из
// 12646; цена по выводу из замера полного бейка (1790 мс / 12646 ламп @ 6
// потоков) — единицы мс. Полный бейк остаётся владельцем ФОРМЫ (top-K-хвосты,
// кластеры, надгробия) — патч её не переписывает, только доливает свет.
struct LightVisPatch {
    struct Hit {
        std::uint32_t cell;
        std::uint32_t lamp;
        float score; // light_cell_score — та же формула, что в полном бейке
    };
    std::vector<Hit> hits; // отсортированы (cell, lamp) — детерминизм слияния
    std::uint32_t affectedLamps = 0;
    float bakeMs = 0.0f;
};

// Перепечь ТОЛЬКО лампы, чей радиус достаёт до карвнутых макроклеток
// (flat macro_index, как CarveResult::dirtyCells). Детерминирован тем же
// приёмом, что полный бейк: чанки ламп, склейка в порядке ламп.
void bake_light_visibility_patch(const MacroGrid& grid,
                                 const LightVisLamp* lamps,
                                 std::size_t lampCount,
                                 const std::uint32_t* carvedCells,
                                 std::size_t nCarved, LightVisPatch& out,
                                 int threads = 0,
                                 const std::atomic<bool>* cancel = nullptr);

// Слить добавки в живые списки. Порядок записей внутри клетки рантайму
// БЕЗРАЗЛИЧЕН (шейдер пересчитывает вклад каждого кандидата — порядок влиял
// только на обрезку при полном бейке), поэтому слияние — аппенд с дедупом:
// ни одна старая запись не теряется. Переполненная клетка: новая лампа
// вытесняет ХУДШЕГО честного по вкладу, только если сама лучше — тот же
// класс ошибки, что top-K полного бейка; каждое вытеснение считается в
// live.overflowCells (молча не режем, S11). changedCells (опц.) получает
// отсортированный список изменённых клеток — ровно то, что заливать на GPU.
// Возвращает число изменённых клеток.
std::size_t light_vis_apply_patch(LightVisBake& live,
                                  const LightVisPatch& patch,
                                  const LightVisLamp* lamps,
                                  std::size_t lampCount,
                                  std::vector<std::uint32_t>* changedCells);

