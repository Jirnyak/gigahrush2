// Комната как ОБЪЕКТ — CANON S12 + решения владельца 2026-08-28
// ([markoaudit/plans/rooms-object.md]).
//
// Комната — это СМЫСЛ, а не материал: планировка этажа, карта мола (S12.1).
// Здесь её предмет: RoomId, к которому крепится всё остальное — вектор
// предложения (S12.4), запас (S12.5), владелец (S14.3), репутация (S13.6),
// собственник места для свидетельства (S19).
//
// Три закона этого файла:
//   1. КОМНАТА = ЗОНА, агностичная к геометрии (владелец 2026-08-28): модуль
//      объявляет 3D-боксы в клетках и НЕ думает о стенах — стены эмерджентны
//      (1 субвоксель или 3 клетки, не константа). Никакого вывода комнат из
//      материи, стрида или хеша. «Квартиры» не существует: комната — элемент
//      соц-алайф-мира, эмерджентно соединённый с соседями.
//   2. Жизненный цикл — закон масок (S18): объявление — чистая функция модуля
//      (kind, number, seed), перештамповывается на generate И restore. В сейв
//      едет только накопленное (репутация; владелец — если сменился). RoomId
//      устойчив, потому что порядок объявления детерминирован.
//   3. roomAt — ЕДИНСТВЕННЫЙ шов (S12.5): плоский u16 на клетку, 4 МиБ на
//      резидентный этаж (решение владельца: платим). В какой комнате агент,
//      чей контейнер, куда упал труп, чья клетка у карва — одно чтение.
//
// Клеточная гранулярность законна: комнаты — макровопрос (S2); субвоксельная
// стена внутри клетки не делит клетку между зонами — модуль сам решает, чья
// она. Вида комнаты НЕТ (S12.2): только вектор глаголов + теги + псевдонимы.
//
// Pure game-layer: no SDL/Vulkan. Headless-tested (suite_rooms_object).
#pragma once

#include <cstdint>
#include <utility>
#include <vector>

#include "game/verb_table.h" // kVerbCount — K из verbs.csv, не литерал

namespace giga::game {

// 0 = не объявлено: коридор, шахта, толща. Коридор — НЕ комната (S12.1):
// то, через что идут, не то, куда идут.
using RoomId = std::uint16_t;
inline constexpr RoomId kNoRoom = 0;

// Теги — глобальный словарь КЛАССОВ комнат (решение владельца 2026-08-28):
// метка для контента и общих механик, НЕ вид. Конкретная авторская комната
// («лаборатория Якова») — псевдоним у модуля, не тег.
inline constexpr std::uint16_t kRoomTagHermetic = 1u << 0; // гермозона (S17: полотно гермокласса)
inline constexpr std::uint16_t kRoomTagNest = 1u << 1;     // логово: авторский контроль гнёзд (S13.7)

// 3D-зона в клетках: origin + size, оси равноправны (S1), координаты
// заворачиваются тором — зона на шве законна, как блок падика на шве.
struct RoomBox {
    std::uint8_t x = 0, y = 0, z = 0;    // origin, wrapped
    std::uint8_t sx = 0, sy = 0, sz = 0; // size >= 1 по каждой оси
};

struct Room {
    std::uint16_t tags = 0;
    // 0 = ничья. Кодировка (NPC против фракции) приезжает с потребителем
    // (инкремент E / S14.3); до него поле — данные объявления.
    std::uint16_t owner = 0;
    std::uint32_t boxFirst = 0; // композиция: боксы в общем пуле FloorRooms
    std::uint16_t boxCount = 0;
    std::uint16_t cells = 0;    // Σ проштампованных клеток (вместимость, гейты)
    // S12.4: ОБЪЯВЛЕНО — неразрушимая часть предложения. Работает с генерации,
    // до всякой расстановки; сожгли диван — вернулось сюда, а не к нулю.
    std::int16_t declared[kVerbCount] = {};
    // S12.4: кэш предложения. Сегодня живут ОСНАЩЕНИЕ+ЗАПАС (room_supply.h);
    // СРЕДА/ФОРМА/НАРОД приезжают со своими системами. i32: Σ по богатой
    // комнате (нажива = рубли) переполняет i16 честной кучей хабара.
    std::int32_t supply[kVerbCount] = {};
};

// Комнаты одного этажа: плотный список + пул боксов + плоский индекс.
// Пересоздаётся на каждом входе (закон 2) — в снимок этажа не едет.
struct FloorRooms {
    std::vector<Room> list;      // плотный, без дыр; RoomId = индекс + 1
    std::vector<RoomBox> boxes;  // композиции всех комнат, подряд
    std::vector<RoomId> roomAt;  // kMacroDim^3, u16; пуст до rooms_reset
    // Псевдонимы модуля: fnv1a(токен) -> id. Линейный список: их единицы
    // на этаж (только авторские комнаты), поиск — по событию, не по тику.
    std::vector<std::pair<std::uint32_t, RoomId>> aliases;
    // Клетки, объявленные дважды. Гейт: 0. Первый объявивший владеет клеткой
    // (детерминизм); второй считается вслух, а не молчит.
    std::uint32_t overlapCells = 0;
    // Отказы room_declare (пустая композиция, нулевой размер). Гейт: 0.
    std::uint32_t refused = 0;
};

// Очистить и подготовить к объявлениям нового этажа (аллоцирует roomAt).
void rooms_reset(FloorRooms& fr);

// Объявить комнату: композиция боксов под одним id, теги, стартовый владелец,
// ОБЪЯВЛЕННОЕ предложение (nullptr = нули). Штампует roomAt сразу; порядок
// вызовов и есть источник устойчивости RoomId. Возвращает kNoRoom (и считает
// refused) на пустую/нулевую композицию — комната без клеток запрещена.
RoomId room_declare(FloorRooms& fr, const RoomBox* boxes, int boxCount,
                    std::uint16_t tags, std::uint16_t owner,
                    const std::int16_t* declared = nullptr);

// В какой комнате клетка (wrap по всем осям). kNoRoom = коридор/толща.
RoomId room_at(const FloorRooms& fr, int x, int y, int z);

const Room* room_of(const FloorRooms& fr, RoomId id);
Room* room_of(FloorRooms& fr, RoomId id);

// Псевдонимы модуля (решение владельца 2026-08-28, образец named_rooms.ts
// референса): контент ссылается на авторскую комнату токеном, не именем для
// игрока (S13.9) и не глобальным битом.
inline constexpr std::uint32_t room_alias_hash(const char* s) {
    std::uint32_t h = 2166136261u; // FNV-1a offset basis
    for (; *s != '\0'; ++s) {
        h ^= static_cast<std::uint32_t>(static_cast<unsigned char>(*s));
        h *= 16777619u; // kFnvPrime (ai.h) — constexpr-копия, тот же алгоритм
    }
    return h;
}
void room_alias(FloorRooms& fr, std::uint32_t aliasHash, RoomId id);
RoomId room_find_alias(const FloorRooms& fr, std::uint32_t aliasHash);

} // namespace giga::game
