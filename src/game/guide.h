//
// То есть закон «писатель один» в проде НЕ ДЕРЖИТСЯ, и держался он не токеном,
// а тем, что два звена цепочки почти всегда молчат. Это и есть довод существования
// этого файла — замер, а не чертёж.
//
// ЧТО ЗДЕСЬ ЛЕЖИТ СЕЙЧАС: примитивы, которыми ведение ОДНО. Каждый из них
// заменил СОБОЙ 3-4 дословных копии — не ради краткости, а потому что копия и
// есть тот дефект, который канон запрещает:
//
//   * `steer_frame_of` ([world/gravity.h]) — плоскость ходьбы, 4 копии;
//   * `steer_tangent` — проекция на неё, 4 копии лямбды;
//   * `steer_to_zone` — «куда шагнуть к зоне», 3 ПОБАЙТОВО одинаковых копии
//     по 30 строк (`wander.cpp`, `place.cpp`, `ai.cpp`);
//   * `steer_write`/`steer_stop` — единственная форма записи скорости и
//     единственная форма остановки, 8 и 5 копий;
//   * `kWalkSpeedMps` — скорость ходьбы, 4 копии числа 1.35 в четырёх файлах,
//     каждая с комментарием «то же, что в `wander.cpp`».
//
// ЧТО ЗДЕСЬ ЛЕЖИТ ТЕПЕРЬ (шаг 2, 2026-11-09): САМ ПРОХОД. `guide_step` —
// единственный писатель горизонтальной `Velocity` агентов; остальные проходы
// ЗАЯВЛЯЮТ ЦЕЛЬ и не касаются скорости вовсе. Токен `MotionOwner` умер по
// построению: арбитрировать нечего, когда писатель физически один.
//
// ВИДОВ ЦЕЛИ У ДВИЖЕНИЯ ТРИ, А НЕ ЧЕТЫРЕ, И ЭТО НЕ УРЕЗАНИЕ КАНОНА.
// CANON S13.3 называет четыре вида цели — комната, сущность, точка, поле — и
// говорит дословно: «виды различаются ровно двумя вещами — КАК ДОЙТИ и ЧТО
// СЧИТАТЬ ПРИБЫТИЕМ». Прибытие — половина ЗАЯВИТЕЛЯ: он и выбирал цель, он и
// знает, когда она достигнута (тело в целевой зоне, жертва в досягаемости,
// шум отработан). Движению остаётся «как дойти», а способов дойти ровно три:
//
//   Zone — нужен нав по зонам (комната/зона: §88, две таблицы, ни одной волны);
//   Dir  — нава не нужно, идти по вектору (сущность, точка и поле СХОДЯТСЯ
//          здесь: заявитель отдаёт пеленг, который сам же и построил —
//          на жертву, на шум, против градиента опасности);
//   Hold — стоять на месте владеемым нулём («сумма сказала оставайся», S24).
//
// Поэтому `Point` отдельным видом НЕ ЗАВЕДЁН: он был бы `Dir` с чужим
// прибытием, то есть столбцом без читателя (закон дерева, [game/action.h]).
//
// АРБИТРАЖ — РАНГ В ЗАЯВКЕ, ОДНО СРАВНЕНИЕ. Прежде его держал токен плюс
// ПОРЯДОК ВЫЗОВОВ в кадре, причём токен читали четыре прохода в четырёх разных
// формулировках, а пятый (`investigate_step`) не читал вовсе — и именно он дал
// замеренные 45 двойных записей. Ранг выражает приоритет ЯВНО и не зависит от
// порядка вызовов: заявка сильного ранга перебивает слабую, тело с заявкой
// получает РОВНО ОДНУ запись скорости, тело без заявки — НОЛЬ записей и
// прошлую скорость (ровно как сегодня при стаггере, когда проход тело не
// посетил).
//
// ОТКАЗ ПАДАЕТ В СТОРОНУ ВЕДЕНИЯ, А НЕ ЗАМИРАНИЯ. Нераспознанный байт ранга
// или вида цели читается как «заявки нет» — тогда тело ведёт самый слабый
