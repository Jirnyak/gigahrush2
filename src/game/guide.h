// СКОРОСТЬ ХОДЬБЫ — ОДИН ДОМ, м/с. Число антропометрическое: средний шаг
// человека 1.35 м/с, и это ЕДИНСТВЕННОЕ его объявление в дереве. Всё
// остальное — МНОЖИТЕЛИ от него (паника, мобы из своей таблицы), потому что
// «быстрее обычного» выражается только через обычное.
//
// До 2026-11-09 оно было выписано ЧЕТЫРЕ РАЗА — `kNpcWalkSpeed@wander.cpp`,
// `kErrandSpeed@ai.h`, `kFleeSpeed@ai.h` (× 1.6), `kFeudWalkSpeed@faction_relations.cpp`
// — и каждая копия несла комментарий «то же 1.35, что в wander.cpp, который там
// file-local». Три из четырёх объясняли, почему они РАВНЫ четвёртой: это и есть
// признак одного числа, живущего в четырёх местах.
inline constexpr float kWalkSpeedMps = 1.35f;

// Паника — МНОЖИТЕЛЬ, а не своя скорость: бегущее тело обязано заметно
// обгонять идущее, иначе интент невидим. ДАТА, крутится свободно.
inline constexpr float kPanicPace = 1.6f;

// Ниже этой квадратичной длины пеленга направления НЕТ: проекция на плоскость
// ходьбы опустошила вектор, либо тело стоит точно в целевой точке. 1e-5 м —
// сотая доля миллиметра: нормировка вектора короче неё усиливает шум float, а
// не несёт пеленг.
//
// ОТДЕЛЬНОЕ ИМЯ, И ЭТО ЛЕЧЕНИЕ. Все три прохода ходьбы сравнивали квадрат
// РАССТОЯНИЯ В МЕТРАХ с `kMinFleeGrad2@game/ai.h`, объявленным как порог
// квадрата ГРАДИЕНТА ПОЛЯ ОПАСНОСТИ. Одно имя на две величины в разных
// единицах — это предельный цикл из §64 в зачатке: поправишь порог полю —
// молча поедет ходьба. Значение то же, вопрос другой.
inline constexpr float kSteerMinBearing2 = 1e-10f;

// ПОЧЕМУ ШАГ К ЗОНЕ НЕ ПОЛУЧИЛСЯ. Отказы НАЗВАНЫ по одному: сложить их в
// «не вышло» значило бы получить прибор, который не умеет сказать, что именно
// не работает (цена этой слепоты замерена на наряде — [game/patrol.h]).
enum class SteerFail : std::uint8_t {
    None = 0,    // шаг есть
    NoRoute,     // маршрута нет: другая компонента связности либо цель в толще
    StepUp,      // единственный шаг — вдоль гравитации: ступенька и есть выход
    NoBearing,   // шаг есть, но пеленга нет (см. kSteerMinBearing2)
};

// Ответ двери «куда шагнуть». `dir` нормирован и лежит в плоскости ходьбы;
// при любом отказе он ноль, и это НЕ скорость — что делать с отказом, решает
// заявитель (у прогулки отдавать некому, у наряда и дела есть кому).
struct SteerStep {
    vec3 dir{0.0f, 0.0f, 0.0f};
    SteerFail fail = SteerFail::None;
};

// Проекция на плоскость ходьбы: компонента вдоль гравитации обнуляется. Четыре
// прохода ведения несли эту лямбду дословно; у трёх из них она звалась
// `tangent`, и две писали `vel.v.x/vel.v.y` НАПРЯМУЮ, то есть врали при любой
// гравитации, кроме -Z (`investigate.cpp`, погоня в `wander.cpp`).
inline vec3 steer_tangent(const GravityFrame& gf, float x, float y, float z) {
    if (gf.axis == 0) x = 0.0f;
    else if (gf.axis == 1) y = 0.0f;
    else z = 0.0f;
    return vec3{x, y, z};
}

// ЕДИНСТВЕННАЯ ФОРМА ЗАПИСИ СКОРОСТИ ВЕДЕНИЯ. Ось гравитации НЕ ТРОГАЕТСЯ
// никогда — её владелец `physics_step` (тяга и прыжок), какой бы осью она ни
// была. Это локомоция, а не полёт.
inline void steer_write(const GravityFrame& gf, Velocity& vel, const vec3& dir,
                        float speed) {
    if (gf.axis != 0) vel.v.x = dir.x * speed;
    if (gf.axis != 1) vel.v.y = dir.y * speed;
    if (gf.axis != 2) vel.v.z = dir.z * speed;
}

// ВЛАДЕЕМЫЙ НОЛЬ — остановка, а не толчок. Нужен там, где отдавать тело
// некому: не обнулить значит оставить телу прошлую скорость, то есть везти
// его дальше решением, которое уже снято.
inline void steer_stop(const GravityFrame& gf, Velocity& vel) {
    if (gf.axis != 0) vel.v.x = 0.0f;
    if (gf.axis != 1) vel.v.y = 0.0f;
    if (gf.axis != 2) vel.v.z = 0.0f;
}

// КУДА ШАГНУТЬ К ЗОНЕ — ОДНА ДВЕРЬ, ДВА ЧТЕНИЯ, НИ ОДНОЙ ВОЛНЫ (§88).
// Таблица зон даёт соседку на пути к цели, плоскость соседки даёт направление
// шага; ступеньку разрешает САМА дверь нава, поэтому ветки на вертикаль у
// потребителя нет — была бы, значит дверь обошли.
//
// Прицел — ЦЕНТР СЛЕДУЮЩЕЙ КЛЕТКИ, а не голый орт `kNavDir`, и разница не
// косметическая: орт ведёт тело из любой точки клетки одинаково, поэтому тело,
// вошедшее по касательной, шло по краю и цеплялось за углы, а центр следующей
// клетки сам стягивает его к середине коридора.
//
// `from` ПАРАМЕТРОМ, а не вычисляется внутри: зона тела нужна заявителю и для
// других вопросов (прибыл ли, выбор следующей ноги, прибор расстояния), и
// спрашивать её дважды значило бы платить за один ответ два раза.
SteerStep steer_to_zone(const ZoneNav& zones, const GravityFrame& gf,
                        const vec3& pos, int cx, int cy, int cz, RoomId from,
                        RoomId target);

