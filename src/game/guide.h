// КАК ДОЙТИ — три способа, и только они (довод о четырёх видах канона — в
// шапке файла). `None` = заявки нет; стоит нулём не для красоты, см. ранг.
enum class TargetKind : std::uint8_t {
    None = 0,
    Hold,  // стоять: владеемый ноль в плоскости ходьбы
    Zone,  // идти в зону: нав по зонам даёт шаг
    Dir,   // идти по пеленгу: заявитель построил вектор сам
    Count
};

// РАНГ ЗАЯВКИ: СИЛЬНЕЕ — БОЛЬШЕ, А НОЛЬ ЕСТЬ «ЗАЯВКИ НЕТ».
//
// ЗНАК ВЫБРАН НЕ ВКУСОМ. Тот же вопрос уже решался у токена, и решение
// доказано машиной: `MotionOwner::Wander == 0`, потому что «отказ забыть
// выставить токен обязан читаться как „ведёт как сегодня“, НИКОГДА как
// „замершая толпа“» ([game/ai.h], гейт `e2e_test` f8_03 на испорченном байте).
// Поставь сильнейший ранг нулём — и зануленная компонента, остаток на трупе,
// свежий эмплейс или заявитель, выставивший цель и забывший ранг, дают ЗАЯВКУ
// БЕГСТВА ВЫСШЕГО ПРИОРИТЕТА на всю толпу. Поэтому порядок перечисления идёт
// от слабого к сильному, а ноль занят сентинелем: любое непонятное значение
// байта (включая мусор ≥ `Count`) читается как «заявки нет», и тело просто
// едет на прошлой скорости — ровно то, что происходит сегодня, когда проход
// не посетил тело по стаггеру.
enum class SteerRank : std::uint8_t {
    None = 0,  // заявки нет
    Walk,      // прогулка: слабейший заявитель, за ним никого
    Chase,     // погоня моба за жертвой
    Feud,      // вражда фракций
    Errand,    // дело: ход к выбранному месту ИЛИ деяние на месте (S24)
    Patrol,    // наряд
    Flee,      // бегство от опасности: сильнейший
    Count
};
constexpr std::size_t kSteerRankCount = static_cast<std::size_t>(SteerRank::Count);

// Имя ранга несёт СВОЙ ЭНУМ КОЛОНКОЙ ([core/table_guard.h]).
struct SteerRankRow {
    SteerRank rank;
    const char* name;
};
inline constexpr SteerRankRow kSteerRankRows[] = {
    {SteerRank::None, "нет"},     {SteerRank::Walk, "прогулка"},
    {SteerRank::Chase, "погоня"}, {SteerRank::Feud, "вражда"},
    {SteerRank::Errand, "дело"},  {SteerRank::Patrol, "наряд"},
    {SteerRank::Flee, "бегство"}};
GIGA_TABLE_BY_ENUM(kSteerRankRows, &SteerRankRow::rank, kSteerRankCount);

// ЦЕЛЬ — то, что заявитель знает, а движение исполняет. Скорость ЗДЕСЬ, а не
// в проходе, и это закон: «быстрее обычного» есть свойство ЗАНЯТИЯ (паника,
// порода моба, множители поведения), а не способа идти. Проход, выбирающий
// скорость сам, завёл бы ветку по заявителю — то есть вернул бы своё движение
// каждому занятию.
struct Target {
    vec3 dir{0.0f, 0.0f, 0.0f};  // Dir: пеленг (ненормированный)
    float speed = 0.0f;          // м/с, уже со всеми множителями
    RoomId zone = kNoRoom;       // Zone
    TargetKind kind = TargetKind::None;
};

inline Target target_hold() {
    Target t;
    t.kind = TargetKind::Hold;
    return t;
}
inline Target target_zone(RoomId zone, float speed) {
    Target t;
    t.kind = TargetKind::Zone;
    t.zone = zone;
    t.speed = speed;
    return t;
}
inline Target target_dir(const vec3& dir, float speed) {
    Target t;
    t.kind = TargetKind::Dir;
    t.dir = dir;
    t.speed = speed;
    return t;
}

// ЗАЯВКА — компонента ECS, живущая ОДИН ТИК. Тик полем, а не «сбросом в конце
// кадра»: сброс есть ещё один проход по телам, то есть декрементный проход,
// который CANON S22 запрещает поимённо («вопрос вместо счётчика делает второго
// писателя невозможным»). Устаревшая заявка не исполняется и видна прибору.
// ТИК — 32 БИТА, И ЭТО ВЫВОД, А НЕ ЭКОНОМИЯ. Везде в дереве тик носится как
// `std::uint64_t`, но заявке он нужен ровно для одного вопроса — «этот тик или
// не этот», — а два тика, различающиеся на 2^32, стоят 397 суток непрерывного
// сима при 125 Гц. Зато 32 бита кладут строку в 28 байт без дыры: `uint64`
// после `Target` дал бы четыре байта паддинга перед собой и ещё семь после
// ранга, то есть 40 — закон контура ровно про это («узкие поля пакуются
// ВМЕСТЕ», [core/row_law.h]).
//
// `GIGA_ROW_HEADERS` в [tools/check_row_law.cmake] этот файл НЕ перечисляет, и
// это та же запись решения, что у `ErrandPlan@game/place.h`,
// `PatrolPlan@game/patrol.h`, `WanderTarget@game/wander.h`: список покрывает
// заголовки, целиком состоящие из строк мира, а здесь рядом с компонентой
// живут ЗНАЧЕНИЯ одного вызова (`SteerStep`, `GuideTick`), которым контур
// памяти ничего не утверждает. Машинный закон при этом стоит — он в двух
// макросах ниже, а не в списке.
struct Steer {
    Target target;
    std::uint32_t tick = 0;
    SteerRank rank = SteerRank::None;
};
GIGA_ROW(giga::game::Steer);
GIGA_ROW_BYTES(giga::game::Steer, 28);

// Заявка действительна ⟺ ранг назван И тик этот. Нераспознанный байт ранга
// читается как «заявки нет» — довод у энума.
inline bool steer_claim_live(const Steer& s, std::uint64_t tick) {
    return s.rank != SteerRank::None && s.rank < SteerRank::Count &&
           s.tick == static_cast<std::uint32_t>(tick);
}

// Прогрев пула ДО открытия вида заявителя. НЕ УДОБСТВО, А СНЯТИЕ УБ: рождение
// ПЕРВОГО элемента нового рода растит контейнер пулов реестра и дангл'ит
// указатели, которые держит ЖИВОЙ вид ([game/place.cpp] — там этот класс и был
// найден аудитом, вместе с опровергнутым комментарием «эмплейс компоненты,
// которой вид не обходит, итерацию не ломает»).
inline void steer_pool_warm(Registry& reg) { (void)reg.storage<Steer>(); }

// «КТО-ТО СИЛЬНЕЕ УЖЕ ЗАЯВИЛ» — замена чтению токена, и спрашивается она В ТОМ
// ЖЕ МЕСТЕ, где стоял токен: ДО всей работы заявителя, а не перед записью
// скорости. Порядок не вкусовой — у вражды и дела есть ПОБОЧНЫЕ ЭФФЕКТЫ
// (выстрел, замах, изъятие предмета из ящика, открытие окна деяния), и
// заявитель, проигравший по рангу уже ПОСЛЕ них, стрелял бы на бегу и ел бы на
// ходу. Сегодня это отрезает `continue` по токену; здесь — этот вопрос.
inline bool steer_claimed_by_stronger(const Registry& reg, Entity e,
                                      SteerRank mine, std::uint64_t tick) {
    const Steer* s = reg.try_get<Steer>(e);
    return s != nullptr && steer_claim_live(*s, tick) && s->rank > mine;
}

// ЗАЯВИТЬ. Слабая заявка поверх сильной НЕ ЛОЖИТСЯ — порядок вызовов в кадре
// на исход не влияет, и это главное отличие от токена: тот работал ровно
// потому, что цепочка стояла в известном порядке, а `investigate_step` этого
// порядка не знал и перебивал прогулку 45 раз за 250 тиков.
//
// ЗАЯВЛЯТЬ СЛЕДУЕТ ТОЛЬКО ТО, ЧТО ИСПОЛНИМО. Заявитель, у которого цель не
// разрешилась (нет маршрута, ступенька, нет пеленга), заявку НЕ ПОДАЁТ — тогда
// тело достаётся следующему по слабости, дословно как сегодня «отдаём вандеру»
// (наряд и дело не забирали токен на отказе). Подать заявку и провалить её
// значило бы отнять тело у того, кто его ещё мог провести.
inline bool steer_claim(Registry& reg, Entity e, std::uint64_t tick,
                        SteerRank rank, const Target& target) {
    const std::uint32_t stamp = static_cast<std::uint32_t>(tick);
    Steer* s = reg.try_get<Steer>(e);
    if (s == nullptr) {
        reg.emplace<Steer>(e, Steer{target, stamp, rank});
        return true;
    }
    if (steer_claim_live(*s, tick) && s->rank > rank) return false;
    s->target = target;
    s->tick = stamp;
    s->rank = rank;
    return true;
}

// Телеметрия прохода. `stale`/`bogus`/`unresolved` обязаны быть НУЛЁМ — это
// самопроверка, а не статистика: заявка не того тика, непонятный байт и цель,
// которую заявитель объявил исполнимой, а проход исполнить не смог.
struct GuideTick {
    std::uint32_t led = 0;         // написана скорость по пеленгу или зоне
    std::uint32_t held = 0;        // написан владеемый ноль (Hold)
    std::uint32_t byRank[kSteerRankCount] = {};
    std::uint32_t stale = 0;       // заявка прошлого тика
    std::uint32_t bogus = 0;       // непонятный байт ранга или вида
    std::uint32_t unresolved = 0;  // Zone без шага у ЗАЯВЛЕННОЙ цели
    std::uint32_t foreign = 0;     // заявка на теле человека или трупа
};

