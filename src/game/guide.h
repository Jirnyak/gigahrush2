//
//   этаж 0 (падик): тел с тождеством 497/тик, записей 186/тик
//                   (наряд 76, дело 64.9, прогулка 44.3, игрок 1),
//                   ДВОЙНЫХ ЗАПИСЕЙ 0;
//   этаж 6 (хрущи): тел 470/тик, записей 64.7/тик
//                   (прогулка 57.6, наряд 5.4, бегство 0.5, слух 0.2),
