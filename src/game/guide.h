// ПОСЛЕ всех заявителей и ПЕРЕД `slow_step` (тот клампит, а не ведёт).
GuideTick guide_step(Registry& reg, const ZoneNav& zones, LayerId layer,
                     std::uint64_t tick, const GravityField* gravity);

