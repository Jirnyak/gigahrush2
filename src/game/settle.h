// ДОСЕЛЕНИЕ — единая система «где телу встать на этаже» (CANON S26).
//
// ЗАМЫСЕЛ ВЛАДЕЛЬЦА (2026-11-12, дословно): «3д экшн идёт только на активном
// этаже… остальные этажи не существуют, не симулятся; фоном симулится глобал
// популяция… хранить точки мобов/нпц не лучшее решение, потому что вернулся на
// этаж — время прошло… каждый модуль тоже не оч, потому что игра полностью
// разрушаемая, поэтому геометрия может измениться до неузнаваемости… так что
// наверное единая система доселения, но надо её оч хорошо чисто системно
// агностично универсально продумать».
//
// ЧТО ИЗ ЭТОГО СЛЕДУЕТ ПО ФОРМЕ:
//   * ГДЕ МОЖНО ЖИТЬ, решает ФАКТИЧЕСКАЯ ГЕОМЕТРИЯ, а не план модуля и не
//     запись дампа: место годно, когда тело в нём помещается и стоит на опоре.
//     Это один предикат на атомах ([sim/physics.h] stand_probe), в системе
//     гравитации этажа.
//   * КУДА СЕЛИТЬ, говорят ЗОНЫ. Зоны (комнаты) объявляет модуль — данными, на
//     каждом входе (S12/S18), и они переживают любое разрушение как объёмы.
//     Модулю не нужно писать ни строки кода расселения: вес зоны — её объём.
//   * ПОЗИЦИИ НЕ ХРАНЯТСЯ НИГДЕ. Тело получает место заново на каждом входе —
//     ключом (у жителя это его номер), поэтому при той же геометрии место то
//     же («на своём слоте»), а при изменившейся — соседнее годное.
//   * ЗАПАСНОЙ ИНСТРУМЕНТ «ПРОСТО ГДЕ-ТО» — та же функция при пустом списке
//     зон: клетки всего тора, где можно стоять.
//
// До этой системы холодные записи сеялись слепым хешем по всему тору, а шов
// воплощения принимал клетку, в которую тело ПОМЕЩАЕТСЯ, не спрашивая опоры.
// Замер `[voploshenie]` на открытой геометрии: 366 тел из 378 рождались в
// небе, 339 разбивались; на плотной — 142 из 420 падали с 1–4 м.
