// МЕСТО СТОЯНИЯ В КЛЕТКЕ: центр тела габарита `half`, стоящего в клетке
// (cx, cy, cz), либо отказ. По касательным осям — центр клетки; вдоль низа
// фрейма подошва примеряется к каждой границе субвокселя клетки, снизу вверх,
// и берётся ПЕРВАЯ, где тело помещается и опёрто. Поэтому перекрытие,
// лежащее ВНУТРИ клетки (этаж в полторы клетки: пол на субвокселе 4), стоит
// наравне с перекрытием на границе — клеткой как единицей высоты вопрос не
// задаётся (S2: локальный вопрос решают атомы).
//
// Клетка НЕврапнутая допустима: метры ответа лежат в `[0, kWorldExtent)`.
bool stand_point_in_cell(const World& world, vec3 half, int cx, int cy, int cz,
                         vec3& centreOut);

// СКОЛЬКО КЛЕТОК ТЕЛО ПЕРЕБИРАЕТ, ПРЕЖДЕ ЧЕМ ПРИЗНАТЬ, ЧТО ЖИТЬ НЕГДЕ.
// Вывод, а не назначение: это объём одного бина зон (ребро 8 клеток = 16 м,
// [room.h] kRoomBinEdge) — той же ступени, которой выбор цели меряет «рядом».
// Не нашлось места в объёме одного бина вокруг своего — этаж здесь
// непригоден, и тело НЕ воплощается (решение владельца: лишние остаются «на
// числе» в макросиме), а не уезжает через полтора в чужой угол.
inline constexpr std::uint32_t kSettleProbeCells =
    static_cast<std::uint32_t>(kRoomBinEdge) * kRoomBinEdge * kRoomBinEdge;

// СОСТОЯНИЕ ОДНОГО ПРИХОДА НА ЭТАЖ. Живёт, пока идёт расселение, и ничего не
// переживает: ни сейва, ни следующего входа.
struct Settlement {
    const World* world = nullptr;
    const FloorRooms* rooms = nullptr;
    // Пространство мест — клетки всех боксов всех зон подряд, в порядке
    // объявления; `boxEnd[b]` — сколько клеток в боксах 0..b. Плоско и без
    // куч на зону: место = число, зона места = двоичный поиск.
    std::vector<std::uint32_t> boxEnd;
    std::uint32_t total = 0; // размер пространства; 0 зон → весь тор
    std::vector<std::uint64_t> taken; // бит на макроклетку: место занято телом
    // Счёт вслух (S11).
    std::uint32_t settled = 0;  // мест выдано
    std::uint32_t homeless = 0; // отказов: предел поиска исчерпан
    std::uint32_t probes = 0;   // клеток перебрано всего
};

// Подготовить расселение по зонам `rooms` на геометрии `world`. Пустой список
// зон законен: пространством мест становится весь тор («просто где-то»).
void settle_begin(Settlement& s, const World& world, const FloorRooms& rooms);

// ВЫДАТЬ МЕСТО телу габарита `half` по ключу `key`. Первое место — функция
// ключа, дальше подряд по пространству мест (в зоне это соседние клетки, за
// краем зоны — следующая объявленная), не дальше `kSettleProbeCells` клеток.
// Истина — `centreOut` готов для `Transform::pos`, клетка помечена занятой.
// Ложь — места нет, ничего не помечено.
//
// Детерминизм: ответ — функция (геометрия, зоны, ключ, уже выданные места).
// Порядок вызовов значим только при споре за одну клетку, поэтому зовущий
// обязан идти в порядке, не зависящем от случая (жители — по возрастанию id).
bool settle_spot(Settlement& s, std::uint32_t key, vec3 half, vec3& centreOut);

// ШОВ ВОПЛОЩЕНИЯ ЖИТЕЛЯ — ОДНА СТРОКА НА ВСЕХ ЗОВУЩИХ: место у доселения, по
// ключу из номера записи и сида этажа, и только потом тело (`embody` либо
// `embody_as_player`). Места нет — `entt::null`, запись остаётся холодной и
// НЕ помечается воплощённой.
//
// Выставлено наружу, потому что шов уже дважды переписывали руками: стенды
// (`suite_hunt`, прогулка в `game_test`) повторяли «embody + разрешитель
// места» своим циклом, и когда закон места сменился, их копии молча поставили
// всю толпу в одну клетку. Второго написания у шва быть не должно.
Entity embody_settled(Registry& reg, NpcPool& pool, NpcId id, LayerId layer,
                      Settlement& s, std::uint32_t floorSeed,
                      bool asPlayer = false);

