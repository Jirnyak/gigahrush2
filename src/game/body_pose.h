// ПОЗА ТЕЛА ИЗ ЧАСТЕЙ — чистые функции кадра и позы (CANON S28.3).
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Поза — одна величина с тремя потребителями: сборка
// трупа (сегменты рождаются в ней), рендер живого тела (части рисуются в
// ней) и суд попадания (часть, в которую попали). Если каждый разложит части
// сам, выйдут три параллельные системы одной позы (находка ревью плана
// 2026-11-25). Поэтому раскладка — ЗДЕСЬ, одной функцией, и сборка трупа
// зовёт её первой.
//
// КАДР, А НЕ МИРОВЫЕ ОСИ (S1, закон изотропии). Верх тела — против
// гравитации этажа, и спрашивается тем же фреймом, что плоскость ходьбы
// (`steer_frame_of`, [world/gravity.h]); перёд — взгляд тела (`Look`),
// спроецированный на эту плоскость. Доли формы ([game/prop_form_table.h])
// лежат в осях кадра: x — перёд, y — лево, z — верх.
//
// ЧИСТО: ни реестра, ни мира — только числа на входе. Своего состояния у
// позы нет (S28.3).
#pragma once

#include <cstdint>

#include "core/math.h"
#include "game/prop_form_table.h"
#include "world/gravity.h"

namespace giga::game {

// Три ортонормальные оси тела в мировых координатах.
struct BodyFrame {
    vec3 fwd{1.0f, 0.0f, 0.0f};
    vec3 left{0.0f, 1.0f, 0.0f};
    vec3 up{0.0f, 0.0f, 1.0f};
};

// Кадр из фрейма гравитации и взгляда. Взгляд вдоль вертикали или нулевой
// (тело без `Look`) — перёд по первой касательной оси фрейма (`tanA`): это
// ось, которую фрейм сам называет первой, а не выбор этой функции.
BodyFrame body_frame(const GravityFrame& g, vec3 look);

// Поворот, кладущий оси части (x, y, z) на оси кадра (перёд, лево, верх).
quat body_frame_quat(const BodyFrame& f);

// Масштаб долей формы: H — рост вдоль оси гравитации, W — поперечник
// (большая из двух касательных полуосей силуэта, ×2).
struct BodyScale {
    float W = 0.0f;
    float H = 0.0f;
};
BodyScale body_scale(const GravityFrame& g, vec3 bodyHalf);

// Поза одной части. `half` — в осях самой части; у сферы (r, r, r).
struct PartPose {
    vec3 pos{0.0f, 0.0f, 0.0f};
    quat q{};
    vec3 half{0.0f, 0.0f, 0.0f};
};

// ПОЗА ПОКОЯ формы: части в долях формы, корень в `rootPos`. Пишет
// `form_def(form).count` поз в `out` (место под kMaxFormSegs) и возвращает
// их число. Порядок — порядок строк формы, корень первым.
std::uint16_t form_rest_pose(FormId form, BodyScale s, const BodyFrame& f,
                             vec3 rootPos, PartPose* out);

} // namespace giga::game
