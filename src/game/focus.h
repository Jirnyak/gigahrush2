// ФОКУС ИНТЕРАКЦИИ — одна цель под прицелом, одна табличка, одно действие.
//
// Редакция владельца 2026-08-28: «должна быть элегантная универсальная
// система для всех интеракций», цель выбирается ПРИЦЕЛОМ. До этого промпты
// были рукописной лестницей if-ов в приложении, где каждый интерактив
// прописан ДВАЖДЫ (табличка отдельно, действие отдельно) — рассинхрон вида
// «действие есть, таблички нет» (кнопки лифта) был гарантирован
// конструкцией.
//
// ЗАКОН: кадр выбирает РОВНО ОДНУ цель — ближайшую вдоль луча взгляда среди
// всех кандидатов; текст таблички берётся из ТАБЛИЦЫ (interactables.csv,
// InteractDef::prompt), а не из литерала у места действия; E исполняет
// ровно то, что показано. Новый интерактив = строка CSV + одна ветка
// исполнения; табличка появляется сама.
//
// Кандидаты двух родов, и оба — данные, а не спецслучаи:
//   * СУЩНОСТИ с Interactable (пропы, ящики, трупы, лут, NPC) — их вид и
//     досягаемость уже в таблице;
//   * ДВЕРНЫЕ ПОРТАЛЫ ([game/door.h]) — у двери нет сущности (полотно есть
//     материя мира), поэтому портал участвует в выборе своей записью.
//
// Прицел, а не близость (решение владельца): цель обязана быть в конусе
// взгляда — «навёл и вижу». Луч не марширует по вокселям: цель в пределах
// своего reach, а стену между глазом и целью отсекает los_clear — тот же
// примитив видимости, что у боя.
#pragma once

#include <cstdint>

#include "core/math.h"
#include "ecs/registry.h"
#include "game/door.h"
#include "game/interact_table.h"
#include "world/level_stack.h"

namespace giga {
class World;
}

namespace giga::game {

struct Focus {
    enum class What : std::uint8_t { None = 0, Entity, Portal };
    What what = What::None;
    Entity entity = entt::null;      // What::Entity
    std::uint32_t portal = kNoPortal; // What::Portal
    InteractKind kind = InteractKind::Terminal; // строка таблицы (для Entity)
    vec3 pos{0.0f, 0.0f, 0.0f};
    float dist = 0.0f;
    bool valid() const { return what != What::None; }
};

// Выбрать цель под прицелом. `eye` — позиция глаза, `dir` — единичный взгляд.
// Кандидат проходит, если он: на этом слое, в пределах СВОЕГО reach (таблица
// для сущностей, kDoorReachM для порталов), в конусе взгляда и виден
// (los_clear). Побеждает ближайший по расстоянию вдоль луча.
Focus focus_pick(const Registry& reg, const World& w, LayerId layer,
                 const vec3& eye, const vec3& dir, const Doors& doors);

// Текст таблички БЕЗ имени клавиши (её подставляет вызывающий из биндов —
// промпт обязан называть бинд, а не литерал). Для двери — по состоянию мира.
const char* focus_prompt(const Focus& f, const World& w, const Doors& doors);

} // namespace giga::game
