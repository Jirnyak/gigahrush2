// СИСТЕМА ПРИСУТСТВИЯ — универсальный пузырь (matwej.md §23, идея владельца
// 2026-11-05, инкремент F0).
//
// ЧТО ЭТО. Единственная в дереве граница между «изотропной симуляцией» и
// «пузырём презентации». Вещи, которые законно удешевлять по удалённости от
// наблюдателя — застывшие рагдоллы, осевший дебрис, динамические источники
// света, декали, — РЕГИСТРИРУЮТСЯ здесь и получают от системы радиус и счёт.
// Своего радиуса не завёл никто: греп по `src/` на имена вида
// `dist_to_player` / `kSimRadius` / `activeRadius` давал НОЛЬ на 2026-11-06, и
// правило в [tools/check_source_rules.cmake] держит этот ноль машинно. Это
// окно, и оно открыто ровно один раз: система построена ДО первого потребителя,
// поэтому миграции нет и старых радиусов нет.
//
// ЗАКОН ДОПУСКА (§23.1). Вещь можно суспендить вне пузыря тогда и только
// тогда, когда «суспендить и возобновить» даёт ТО ЖЕ состояние мира, что «не
// суспендить вовсе»: суспенд обязан КОММУТИРОВАТЬ с миром. Отсюда три класса:
//
//   kFreeze   (класс 1) — вне пузыря не считается вовсе, возобновление точное.
//                         Гейт: дайджест мира при радиусе ∞ и при настоящем
//                         радиусе равен БИТ-В-БИТ.
//   kCoarsen  (класс 2) — вне пузыря считается грубее; расхождение есть, но
//                         ограничено и объявлено числом. Гейт другой: выход
//                         потребителя НЕ ВХОДИТ в дайджест мира вовсе.
//   запрещено (класс 3) — расхождение не ограничено ИЛИ состояние кормит
//                         навигацию / проходимость / нужды / решатель. Такой
//                         потребитель здесь не регистрируется, и регистрация
//                         его есть дефект, а не настройка (matwej.md §24.8 —
//                         это решение владельца, а не моё). Поэтому жидкостям
//                         и газам ОТКАЗАНО: замороженный разлив делает
//                         навигацию проходимой там, где была бы вода.
//
// ПОЧЕМУ РАДИУС — НОМИНАЛ, А НЕ ЖИВОЕ ЧИСЛО (решение владельца 2026-11-06).
// Уровни берут НОМИНАЛЬНЫЕ доли периода тора (`kFogStartFrac`/`kFogEndFrac`,
// [world/types.h]) и НЕ умножаются ни на погодный `samosbor_fog_scale`, ни на
// отладочный `GIGA_FOGMUL`. Это не упрощение, это требование §23.1: живой
// множитель сделал бы радиус ФУНКЦИЕЙ СОСТОЯНИЯ МИРА — самосбор сжимал бы
// полный пузырь 64 → 21.8 м (×0.34), то есть «суспендить и возобновить»
// перестало бы коммутировать именно в тот момент, когда в мире что-то
// происходит; а env-ручка сделала бы состояние симуляции функцией отладочной
// переменной окружения. Погодное сжатие остаётся тем, чем всегда было —
// делом РЕНДЕРА, в `push.fog` ([app/main.cpp]).
//
// СЧЁТ ВАЖНЕЕ РАДИУСА, И ОН У КАЖДОГО СВОЙ (§23.3). Радиус не ограничивает
// цену, потому что плотность неизвестна: 64 м в пустом коридоре и 64 м в
// плотном зале — разная работа. Поэтому потребитель регистрируется не
// радиусом, а БЮДЖЕТОМ и ЗАМЕРЕННОЙ ценой штуки, а число штук выводится:
//
//     N = budget_ms × 1000 / cost_per_item_us
//
// и печатается ВМЕСТЕ со своим выводом и с указанием замера, из которого взята
// цена. `N` без напечатанного вывода есть дефект (закон «константы обязаны
// выводиться»).
//
// ЧЕГО ЗДЕСЬ НЕТ СОЗНАТЕЛЬНО. Своего пространственного индекса: запрос идёт
// через `CellBins::nearest_in_radius` ([sim/cell_bins.h]) — ту же дверь, что
// отвечает «кто рядом» всему остальному дереву, расширенную, а не
// продублированную. Политики «что делать с выборкой» — решает потребитель;
// система отвечает на «кто и сколько», и только.
//
// СЛОЙ. `sim/`. Вниз по дереву зависимостей: `core` → `world` → `sim`. Ни
// `game/`, ни `render/`, ни `app/` отсюда не видны и видны быть не могут —
// потребитель из верхнего слоя РЕГИСТРИРУЕТСЯ (инъекция), система о нём не
// знает ничего, кроме строки имени и двух чисел. Та же форма, что у
// `WalkBits::build` и у `rigid_attach_*`: параметры приносит каллер.
#pragma once

#include <cstdint>

#include "core/math.h"
#include "ecs/registry.h"
#include "sim/cell_bins.h"
#include "world/types.h"

namespace giga {

// ---- УРОВНИ -----------------------------------------------------------------
// Два, и оба — доли периода тора, выведенные в [world/types.h]. Третьего
// («ВНЕ») в перечислении нет сознательно: «вне» — это не уровень, а ответ
// запроса «не попал», и заводить для него имя значило бы заводить состояние,
// которого никто не хранит.
enum class PresenceLevel : std::uint8_t {
    kFull = 0,    // d ≤ 64 м — где только НАЧИНАЕТСЯ дымка
    kVisible = 1, // d ≤ 128 м — предел однозначной дальности на торе (tCap)
};

// Класс решает, КАКОЙ гейт применяется к потребителю (§23.2). Класс 3 здесь
// не представлен и представлен быть не может: отсутствие имени — и есть
// запрет, потому что незарегистрированный потребитель системы не существует.
enum class PresenceClass : std::uint8_t {
    kFreeze = 0,  // не считать вовсе; дайджест мира обязан совпасть бит-в-бит
    kCoarsen = 1, // считать грубее; выход обязан не входить в дайджест вовсе
};

inline constexpr float kPresenceFullRadius = kWorldExtent * kFogStartFrac;
inline constexpr float kPresenceVisibleRadius = kWorldExtent * kFogEndFrac;
static_assert(kPresenceFullRadius == 64.0f, "полный пузырь = старт дымки");
static_assert(kPresenceVisibleRadius == 128.0f, "видный пузырь = tCap марша");

// Радиус уровня в метрах. ЕДИНСТВЕННАЯ дверь к радиусу пузыря во всём дереве.
float presence_level_radius(PresenceLevel level);

// ---- ЦЕНТРЫ -----------------------------------------------------------------
// ЦЕНТРОВ МНОЖЕСТВО, А НЕ ОДИН, и это заложено сразу, потому что потом дорого
// (§23.3 п.1): [netcode.md] объявляет server-authoritative с первого дня, и
// сессия там — «членство клиента на сервере», каждая со своим воплощённым
// телом; два игрока = два пузыря. Список вместо точки стоит одну строку
// сейчас и переписывание всех потребителей потом.
//
// ЦЕНТР — КАМЕРА, А НЕ ТЕЛО (§23.3 п.2). В игре есть консольный полёт
// (`fly`), и тело при этом остаётся на месте; пузырь обязан ехать за взглядом,
// иначе в полёте мир вокруг игрока застывает. Поэтому центр приносит каллер
// (`compute_camera(...).eye`, [sim/camera.h]), а система не ищет игрока сама —
// у неё и нет способа: синглтона игрока в этом движке не существует.
//
// ВЫВОД КАПА = 8, И ЭТО ТЕОРЕМА, А НЕ ДОГАДКА О ЧИСЛЕ ИГРОКОВ.
// 8 — максимальное число ПОПАРНО НЕ ПЕРЕСЕКАЮЩИХСЯ полных пузырей на этом
// торе, то есть предел, за которым список центров перестаёт описывать новые
// области присутствия и начинает описывать толщину уже имеющихся.
//   * достижимо: центры решётки {0, 128}³ попарно удалены на 128, 128√2 и
//     128√3 метров, то есть все ≥ 2R = 128 при R = 64 — восемь пузырей
//     касаются, но не пересекаются;
//   * недостижимо больше: на окружности периода 256 две метки 0 и 128 делят её
//     на две дуги по 128, поэтому ЛЮБАЯ координата удалена от ближайшей метки
//     не более чем на 64; значит для любой точки тора ближайший узел решётки
//     ближе чем 64√3 = 110.9 < 128 — девятый центр обязан пересечь чей-то
//     пузырь.
// Отсюда и форма: фиксированный встроенный массив, аллокаций на кадре нет
// (тот же закон, что у `CellBins`). Кап СЧИТАЕТСЯ и ПЕЧАТАЕТСЯ при переливе —
// молча не режем (S11). Сегодня центр ровно один: `compute_camera` возвращает
// первую найденную камеру, и `CameraTag` в дереве один.
inline constexpr std::uint32_t kMaxPresenceCenters = 8;

// Поставить центры кадра. Зовётся КАЖДЫЙ кадр: система не помнит прошлый кадр
// и не экстраполирует — присутствие есть свойство ЭТОГО кадра.
// Лишние центры сверх капа отбрасываются и считаются (см. presence_report).
void presence_set_centers(const vec3* centers, std::uint32_t n);
std::uint32_t presence_center_count();

// ---- РЕГИСТРАЦИЯ ------------------------------------------------------------
using PresenceId = std::uint32_t;
inline constexpr PresenceId kInvalidPresenceId = 0xFFFFFFFFu;

// Белый список потребителей ПОИМЁННЫЙ и печатается (§23.6). Кап — не правило
// мира, а размер встроенной таблицы: потребители §23.7 суть рагдоллы, дебрис,
// декали, частицы, скиннинг пропов и свет, то есть единицы; 16 даёт запас
// вдвое и переполнение ПЕЧАТАЕТ, а не режет молча.
inline constexpr std::uint32_t kMaxPresenceConsumers = 16;

struct PresenceRegistration {
    const char* name = nullptr;       // ПОИМЁННО: попадёт в печать белого списка
    PresenceLevel level = PresenceLevel::kFull;
    PresenceClass cls = PresenceClass::kFreeze;
    float budget_ms = 0.0f;           // решение владельца
    float cost_per_item_us = 0.0f;    // ЗАМЕР, не оценка — ноль ОТКАЗЫВАЕТ
    const char* cost_source = nullptr; // откуда замер: документ, строка, сцена
};

// Зарегистрировать потребителя. Возвращает id либо kInvalidPresenceId при
// отказе, и ЛЮБОЙ отказ печатает причину — регистрация, провалившаяся молча,
// означала бы потребителя, который думает, что он в системе.
//
// ОТКАЗЫ И ИХ ПРИЧИНЫ:
//   * cost_per_item_us ≤ 0 — цена штуки ОБЯЗАНА быть замером. Ноль дал бы
//     N = ∞, то есть «бюджета нет», одетое в язык бюджета; это худший вид
//     числа без вывода, потому что выглядит как решение.
//   * имени нет — белый список обязан быть поимённым (§23.6).
//   * таблица полна — см. kMaxPresenceConsumers.
// budget_ms = 0 отказом НЕ является: это законное «сейчас не платим», и
// N = 0 — честный ответ, а не ошибка.
PresenceId presence_register(const PresenceRegistration& reg);

// N = budget_ms × 1000 / cost_per_item_us, усечённое вниз. Выведено, не
// назначено; печатается presence_report() вместе со слагаемыми вывода.
std::uint32_t presence_budget_n(PresenceId id);

// Радиус потребителя = радиус его уровня. Отдельная дверь, чтобы потребитель
// (например отбор ламп в таблицу) мог взять ТОЛЬКО радиус, не трогая счёт.
float presence_radius(PresenceId id);

// Размер белого списка. Свидетель того, что ОТКАЗ не занимает слот: иначе
// отказанный потребитель числился бы в списке зарегистрированных, а список
// зарегистрированных и есть доказательство законности (§23.6).
std::uint32_t presence_consumer_count();

// ПОКОЛЕНИЕ ТАБЛИЦЫ. Растёт на каждом presence_reset(). Нужно потому, что
// потребитель кэширует свой id в статике (регистрация — один раз), а сброс
// таблицы делает кэш ЛОЖЬЮ: id остаётся прежним, а за ним больше ничего нет, и
// потребитель молча получает N = 0 — то есть «всё за бортом пузыря». Поймано
// на себе в [sim/rigid.cpp]: сюита присутствия зовёт reset в том же бинарнике,
// что и пины рагдоллов. Кэшируй ПАРУ (id, поколение), а не id.
std::uint32_t presence_generation();

// ---- ЗАПРОС -----------------------------------------------------------------
// N ближайших внутри радиуса уровня, расстояние — до БЛИЖАЙШЕГО из центров
// (два центра дают ОБЪЕДИНЕНИЕ выборок, не пересечение).
//
// `bins` приносит потребитель: бины строятся по ЕГО населению (рагдоллы — по
// телам, дебрис — по осевшим куускам), и строить их за него значило бы
// завести здесь второй проход по миру. Позиции читаются из `Transform`.
//
// Возвращает число записанных в `out` (≤ min(N, outCap)). Счётчики попаданий
// и отбросов копятся у потребителя и печатаются presence_report() — предикат
// обязан говорить, сколько он выкинул (§24.4 п.5).
std::uint32_t presence_query(PresenceId id, const CellBins& bins,
                             const Registry& reg, CellBins::Near* out,
                             std::uint32_t outCap);

// Счётчик потребителя, которому присутствие дало радиус, но не счёт — сегодня
// это отбор ламп в таблицу: он проверяет попадание в радиус сам, в своих трёх
// циклах по разным видам сущностей, и бинов у него нет. Чтобы его отбраковка
// не осталась немой, он СООБЩАЕТ её сюда одной строкой, и дальше она печатается
// тем же прибором, что и отбраковка запроса.
void presence_note(PresenceId id, std::uint32_t considered,
                   std::uint32_t passed);

// ---- ШОВ ГЕЙТА КОММУТАЦИИ (§23.1 / §23.6) -----------------------------------
// Прогон «всё живое»: радиус = ∞ и счёт не ограничен. Дайджест-гейт сличает
// такой прогон с настоящим и обязан получить БИТ-В-БИТ равное состояние мира;
// он включится ПЕРВЫМ ПОТРЕБИТЕЛЕМ КЛАССА 1 (F1, рагдоллы) — до него сличать
// нечего, потому что единственный сегодняшний потребитель класса 2 и в
// дайджест мира не входит по определению своего класса.
//
// Шов оставлен сейчас по одной причине: он обязан быть ОДНИМ флагом в ОДНОМ
// месте. Если его добавлять вместе с F1, он будет добавлен как параметр в
// рагдолльный проход — то есть как второй радиус, против которого вся эта
// система и построена.
void presence_force_infinite(bool on);
bool presence_forced_infinite();

// ---- ПРИБОР -----------------------------------------------------------------
// Печатает БЕЛЫЙ СПИСОК ПОИМЁННО (§23.6) и у каждого потребителя: уровень,
// класс, радиус, бюджет, цену штуки, источник замера, выведенное N и то,
// сколько он на прошлом кадре рассмотрел / пропустил / отбросил. Формат —
// `[presence]`, по образцу строк `[nav]` / `[diffuse]`.
//
// Отдельно печатается и переполнение центров: кап, который режет молча, есть
// кап, ставший правилом мира (§24.4 п.7).
void presence_report();

// ---- ЧЕСТНАЯ ГРАНИЦА: У КОГО ЗДЕСЬ НЕТ ВЫЗЫВАЮЩЕГО ВНЕ ТЕСТОВ --------------
// «API без потребителя — дефект, а не задел» (matwej.md §24.5), поэтому список
// написан, а не оставлен на греп следующему читателю. На 2026-11-06:
//
//   ЖИВЫЕ (зовёт [app/main.cpp], отбор ламп в таблицу — потребитель класса 2):
//     presence_register, presence_radius, presence_set_centers,
//     presence_note, presence_report; presence_level_radius — изнутри.
//
//   ЗОВУТ ТОЛЬКО ТЕСТЫ, И ВЫЗЫВАЮЩИЙ НАЗВАН ЗАРАНЕЕ:
//     presence_query, presence_budget_n — первый потребитель класса 1, то есть
//       рагдоллы F1 (§23.7: N = 128, уровень kFull). Отбор ламп их не зовёт по
//       своему устройству: он проверяет попадание в радиус сам, в трёх циклах
//       по разным видам сущностей, и бинов у него нет.
//     presence_force_infinite, presence_forced_infinite — шов дайджест-гейта
//       коммутации, включается тем же F1 (причина, по которой он стоит уже
//       сейчас, — абзацем выше).
//     presence_reset, presence_center_count, presence_consumer_count —
//       тестовая оснастка и свидетели, по назначению.
//
// Если F1 не придёт, этот блок есть расписка: перечисленное надо СНОСИТЬ, а не
// оставлять «на будущее» — тест, переживший свой предмет, есть будущая вторая
// реализация.

// Обнулить всё: таблицу потребителей, центры, счётчики, флаг ∞. ЭТО ДЛЯ
// ТЕСТОВ, чтобы сюиты не наследовали друг у друга состояние. В игре звать
// НЕЛЬЗЯ: потребители держат свой id в статике (регистрация — один раз за
// процесс), и обнуление таблицы под ними превратило бы живой id в чужой.
void presence_reset();

} // namespace giga
