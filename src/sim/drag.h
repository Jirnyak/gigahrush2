// Трение воздуха — ОДИН квадратичный закон для всего, что несёт Velocity.
//
//   F = -k * |v|^2 * v̂,   k = kAirDragCoef * A(AABB)
//
// k выводится из Mass и AABB — одна формула, ноль таблиц. A — средняя площадь
// грани бокса: изотропная прокси сечения (x/y/z равноправны, [AGENTS.md]
// изотропия), чтобы закон не завёл осевую букву. Следствие закона —
// ТЕРМИНАЛЬНАЯ СКОРОСТЬ: v_t = sqrt(g / q), где q = k/m. Вечное падение в
// шахте тора превращается в падение с капом; тело 70 кг в боксе 0.8x0.8x1.8
// капится на ~55 м/с, пуля на дистанции выстрела почти не теряет (её AABB мал,
// а Mass-фолбэк общий), плотный обломок бетона падает быстрее тела — всё из
// одной формулы, без единой ветки по типу сущности.
//
// Живёт в ЯДРЕ (src/sim), а не в игре, по той же причине, что SelfIntegrating:
// интеграторов ДВА — physics_step (src/sim) для тел и projectile_step
// (src/game) для снарядов — и оба обязаны применять ТОТ ЖЕ закон, а src/sim не
// может включать src/game. Обе точки зовут эти три функции; второй формулы нет.
#pragma once

#include "core/math.h"

namespace giga {

// 1/2 * rho * Cd, свёрнутые в одну игровую ручку (кг/м^3). Подобрана из
// терминальной скорости тела: v_t = sqrt(m*g / (k*A)) = 55.5 м/с для 70 кг в
// дефолтном AABB — внутри одобренной полосы 50-60. Вторая ручка схемы (порог
// сгорания) появится вместе с самим сгоранием; здесь только трение.
inline constexpr float kAirDragCoef = 0.19f;

// Средняя площадь грани AABB (м^2). Не проекция по направлению движения —
// та дёргалась бы на каждом повороте вектора и дарила бы дешёвый анизотропный
// эксплойт (падать «узкой стороной»); среднее по трём граням изотропно и
// стоит три умножения.
inline constexpr float drag_area(vec3 half) {
    return 4.0f * (half.x * half.y + half.y * half.z + half.z * half.x) / 3.0f;
}

// q = k/m (1/м) — всё, что нужно интегратору. Масса снизу зажата, чтобы
// нулевая/мусорная строка контента дала большое трение, а не inf/NaN в
// скорости всего, что этим q тронут.
inline constexpr float drag_q(vec3 half, float massKg) {
    return kAirDragCoef * drag_area(half) / (massKg > 0.01f ? massKg : 0.01f);
}

// Один шаг трения: v *= 1 / (1 + q*|v|*h) — ТОЧНОЕ решение dv/dt = -q*|v|*v,
// не эйлеров шаг. Что это покупает: устойчивость на любом h (скорость только
// убывает, никогда не меняет знак, как сделал бы явный Эйлер при большом q*v*h)
// и точную арифметику терминала — неподвижная точка цикла «гравитация +h*g,
// затем этот шаг» есть в точности q*v^2 = g, то есть v_t = sqrt(g/q) при любом
// шаге интегратора. Тест пинит именно это равенство.
inline void air_drag_step(vec3& v, float q, float h) {
    const float speed = length(v);
    if (speed <= 1e-6f) return;
    v = v * (1.0f / (1.0f + q * speed * h));
}

} // namespace giga
