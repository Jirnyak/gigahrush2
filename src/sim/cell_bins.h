// Клеточные бины — ОДИН примитив пространственного поиска «кто в этой
// макроклетке» (S11: один закон ключа и один контейнер; ПОЛИТИКА — у
// потребителя). До 2026-08-21 выражение ключа (layer<<32)|macro_index было
// выписано четырежды в rigid.cpp и ещё раз в prop_system.cpp, а контейнер
// «отсортированные (ключ, сущность)» — трижды. Потребители и их политика:
//
//   - sim/rigid.cpp     — пере-сборка раз на тик по подвижным телам; поверх
//                         бинов свой алгоритм: слияние отсортированных рангов
//                         в пары соседних клеток (13 передних смещений);
//   - game/prop_system  — §59.2: ПЕРСИСТЕНТНЫЕ бины неподвижных якорей,
//                         инвалидация сигналами EnTT на SubVoxelAnchor;
//   - game/combat       — §59.3: пере-сборка на вызов по толпе, ближайший
//                         к снаряду в 27 соседних бакетах.
//
// Контейнер = плоский вектор (ключ, сущность), отсортированный build()-ом;
// запрос — lower_bound. Никаких карт и аллокаций на запрос; память живёт у
// владельца и переиспользуется через clear().
#pragma once

#include <algorithm>
#include <cmath>
#include <cstdint>
#include <vector>

#include "core/math.h"
#include "core/wrap.h" // wrap_dist2 — торическое расстояние всеми ТРЕМЯ осями
#include "ecs/registry.h"
#include "world/types.h"

namespace giga {

// Закон ключа — единственное место, где (слой, клетка) складываются в u64.
// Слой в старших битах: сортировка группирует сначала по слою, потом по
// плоскому индексу клетки — на этом стоит слияние соседей в rigid.cpp
// (ключ соседа = ключ + константа при фиксированном смещении).
inline std::uint64_t cell_bin_key(std::uint32_t layer, int cx, int cy, int cz) {
    return (static_cast<std::uint64_t>(layer) << 32) |
           static_cast<std::uint32_t>(
               macro_index(wrap_macro(cx), wrap_macro(cy), wrap_macro(cz)));
}

// Макроклетка непрерывной координаты. std::floor, не int-каст: позиция чуть
// ниже нуля обязана уйти в клетку −1 (и завернуться), а не обрезаться к 0.
inline int cell_coord(float v) {
    return static_cast<int>(std::floor(v / kCellSize));
}

struct CellBins {
    struct Entry {
        std::uint64_t key;
        Entity e;
    };
    std::vector<Entry> entries; // после build() отсортированы по (key, e)

    void clear() { entries.clear(); }
    void add(std::uint64_t key, Entity e) { entries.push_back({key, e}); }

    // Порядок (ключ, сущность) детерминирован и не зависит от порядка
    // вставки: «первый найденный» у потребителя — свойство мира, а не
    // памяти (родня запрета фиксированных префиксов, S13.9).
    void build() {
        std::sort(entries.begin(), entries.end(),
                  [](const Entry& a, const Entry& b) {
                      return a.key != b.key ? a.key < b.key : a.e < b.e;
                  });
    }

    template <class F>
    void for_each_in(std::uint64_t key, F&& f) const {
        auto it = std::lower_bound(
            entries.begin(), entries.end(), key,
            [](const Entry& a, std::uint64_t k) { return a.key < k; });
        for (; it != entries.end() && it->key == key; ++it) f(it->e);
    }

    // Брод-фейз точки: 27 клеток вокруг (cx,cy,cz) на слое, wrap честный.
    // Покрывает точечный запрос радиуса ≤ kCellSize к сущностям, забиненным
    // по клетке ЦЕНТРА, — потребитель обязан заявить это static_assert-ом
    // на свой радиус (образец: kProjHitRadius в combat.cpp).
    template <class F>
    void for_each_near(std::uint32_t layer, int cx, int cy, int cz,
                       F&& f) const {
        for (int dz = -1; dz <= 1; ++dz)
            for (int dy = -1; dy <= 1; ++dy)
                for (int dx = -1; dx <= 1; ++dx)
                    for_each_in(cell_bin_key(layer, cx + dx, cy + dy, cz + dz),
                                f);
    }

    // Запись отбора: квадрат торического расстояния до БЛИЖАЙШЕГО из центров.
    struct Near {
        float d2;
        Entity e;
    };

    // ---- N БЛИЖАЙШИХ В РАДИУСЕ R — РАСШИРЕНИЕ ЭТОЙ ДВЕРИ, А НЕ ВТОРАЯ ------
    //
    // ПОЧЕМУ ЗДЕСЬ. «Кто рядом» в этом дереве отвечает ОДИН примитив (шапка
    // файла, S11), и запрос «N ближайших» — это тот же вопрос с другой
    // политикой отбора. Системе присутствия ([sim/presence.h]) своего
    // пространственного индекса не нужно, и завести его значило бы развести
    // два ответа на один вопрос (matwej.md §24.1 п.5: узкую дверь РАСШИРЯЮТ).
    //
    // КОНТРАКТ РАДИУСА — ДРУГОЙ, ЧЕМ У `for_each_near`, И ЭТО ГЛАВНОЕ, ЧТО
    // НАДО ПРОЧЕСТЬ. `for_each_near` обходит 27 КЛЕТОК, поэтому его радиус
    // заперт на kCellSize = 2 м. Здесь обход идёт по ЗАПИСЯМ (`entries`),
    // поэтому радиус ЛЮБОЙ — он не ограничен ничем, а цена не зависит от него
    // вовсе: O(записей) расстояний независимо от R, от выборки и от плотности.
    // Это сознательный обмен, и он считается: при R = 64 м охват в клетках по
    // 2 м есть куб со стороной 2·(64/2)+1 = 65, то есть 274 625 клеточных
    // поисков на ОДИН запрос; при R = 128 м — 129³ = 2 146 689, фактически
    // весь тор. Полный обход записей дешевле этого на любом населении, которое
    // этот движок держит (кап акторов 4096 — контракт §16). Образец обхода «по
    // записям, не по клеткам» в этом же дереве — пары соседних клеток в
    // [sim/rigid.cpp] (слияние отсортированных рангов, 13 передних смещений).
    //
    // ЦЕНА КОНСТАНТНА ПО СОДЕРЖИМОМУ, и это ДОСТОИНСТВО, а не лень — тот же
    // закон, по которому владелец оставил константной цену скана излучателей
    // (problems.md §78: «в DOD хорошо, когда системы не зависят от заполнения
    // редактором»). Отбор N делается ЧАСТИЧНО, куче на N, а не сортировкой
    // всего: O(M·log N) сравнений вместо O(M·log M), и память — ровно буфер
    // вызывающего (аллокаций на запрос нет, как и обещает шапка файла).
    //
    // ПОРЯДОК ВЫХОДА ДЕТЕРМИНИРОВАН И НЕ ЗАВИСИТ ОТ ПАМЯТИ: ключ сравнения —
    // (d2, сущность), то есть равные расстояния разводятся id, а не адресом.
    // Без этого «N ближайших» на симметричной сцене отвечали бы по-разному в
    // двух прогонах, и дайджест коммутации (matwej.md §23.1) ловил бы шум
    // вместо дефекта. Это та же причина, по которой `build()` сортирует по
    // (ключ, сущность), а не только по ключу.
    //
    // ЦЕНТРОВ МНОЖЕСТВО: расстояние записи = минимум по центрам, то есть два
    // центра дают ОБЪЕДИНЕНИЕ своих выборок, а не пересечение. Один центр —
    // частный случай, не отдельная ветка.
    //
    // `outEligible` — сколько записей прошли радиус. Разность с возвращённым
    // числом есть то, что отбросил БЮДЖЕТ, и потребитель обязан это печатать
    // (matwej.md §24.4 п.5: слишком узкий предикат молча выкидывает из мира).
    // `period` приносит вызывающий: ядро не тянет kWorldExtent из `world/`
    // ровно по той причине, что названа в [core/wrap.h].
    template <class PosFn>
    std::uint32_t nearest_in_radius(const vec3* centers,
                                    std::uint32_t nCenters, float radius,
                                    float period, PosFn&& pos, Near* out,
                                    std::uint32_t outCap,
                                    std::uint32_t* outEligible = nullptr) const {
        if (outEligible) *outEligible = 0;
        if (nCenters == 0 || centers == nullptr) return 0;
        const float r2 = radius * radius;
        // ПОРЯДОК ОТБОРА: ближе — раньше; при РАВНОМ расстоянии раньше тот, у
        // кого меньше id. Это и есть разведение равных по сущности, а не по
        // адресу. `push_heap` с этим сравнением строит МАКС-кучу, то есть в
        // `out[0]` лежит САМЫЙ ДАЛЬНИЙ из оставленных — поэтому вытеснение
        // стоит одно сравнение, а не поиск максимума.
        auto closer = [](const Near& a, const Near& b) {
            return a.d2 != b.d2 ? a.d2 < b.d2 : a.e < b.e;
        };
        std::uint32_t n = 0;
        std::uint32_t eligible = 0;
        for (const Entry& en : entries) {
            const vec3 p = pos(en.e);
            float best = wrap_dist2(centers[0], p, period);
            for (std::uint32_t c = 1; c < nCenters; ++c) {
                const float d2 = wrap_dist2(centers[c], p, period);
                if (d2 < best) best = d2;
            }
            if (!(best <= r2)) continue; // NaN позиция тоже не проходит
            ++eligible;
            if (outCap == 0) continue;
            const Near cand{best, en.e};
            if (n < outCap) {
                out[n++] = cand;
                std::push_heap(out, out + n, closer);
            } else if (closer(cand, out[0])) {
                // Кандидат ближе самого дальнего из оставленных — тот уходит.
                std::pop_heap(out, out + n, closer);
                out[n - 1] = cand;
                std::push_heap(out, out + n, closer);
            }
        }
        if (outEligible) *outEligible = eligible;
        // Сортировка только при непустой выборке: примитив вправе позвать с
        // out = nullptr и outCap = 0 — «сколько их вообще в радиусе», без
        // буфера, — и пара nullptr-итераторов в std::sort это уже UB.
        if (n > 0) std::sort(out, out + n, closer);
        return n;
    }
};

} // namespace giga
